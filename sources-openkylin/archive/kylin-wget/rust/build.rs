//! 编译期读取 `po/*.po`，生成嵌入翻译表（无需链接 libintl）。

use std::collections::HashMap;
use std::env;
use std::fs;
use std::path::PathBuf;

fn main() {
    let out = PathBuf::from(env::var("OUT_DIR").unwrap());
    let manifest = PathBuf::from(env::var("CARGO_MANIFEST_DIR").unwrap());
    let po_dir = manifest.join("po");
    println!("cargo:rerun-if-changed=po");

    let mut catalogs: Vec<(String, HashMap<String, String>)> = Vec::new();
    if po_dir.is_dir() {
        let mut entries: Vec<_> = fs::read_dir(&po_dir)
            .unwrap()
            .filter_map(|e| e.ok())
            .map(|e| e.path())
            .filter(|p| p.extension().and_then(|s| s.to_str()) == Some("po"))
            .collect();
        entries.sort();
        for path in entries {
            let stem = path.file_stem().unwrap().to_string_lossy().to_string();
            let text = fs::read_to_string(&path).unwrap();
            catalogs.push((stem, parse_po(&text)));
            println!("cargo:rerun-if-changed={}", path.display());
        }
    }

    let mut out_rs = String::from("// @generated by build.rs from po/*.po — do not edit.\n\n");
    out_rs.push_str("pub struct Catalog {\n");
    out_rs.push_str("    pub lang: &'static str,\n");
    out_rs.push_str("    pub pairs: &'static [(&'static str, &'static str)],\n");
    out_rs.push_str("}\n\n");
    out_rs.push_str("pub static CATALOGS: &[Catalog] = &[\n");
    for (lang, map) in &catalogs {
        out_rs.push_str(&format!("    Catalog {{ lang: \"{lang}\", pairs: &[\n"));
        let mut keys: Vec<_> = map.keys().collect();
        keys.sort();
        for k in keys {
            let v = &map[k];
            out_rs.push_str(&format!(
                "        ({}, {}),\n",
                rust_str(k),
                rust_str(v)
            ));
        }
        out_rs.push_str("    ]},\n");
    }
    out_rs.push_str("];\n");
    fs::write(out.join("i18n_catalogs.rs"), out_rs).unwrap();
}

fn rust_str(s: &str) -> String {
    let escaped: String = s
        .chars()
        .map(|c| match c {
            '\\' => "\\\\".to_string(),
            '"' => "\\\"".to_string(),
            '\n' => "\\n".to_string(),
            '\r' => "\\r".to_string(),
            '\t' => "\\t".to_string(),
            c if c.is_control() => format!("\\u{{{:04x}}}", c as u32),
            c => c.to_string(),
        })
        .collect();
    format!("\"{escaped}\"")
}

/// 极简 GNU .po 解析（msgid / msgstr，支持连续字符串拼接）。
fn parse_po(text: &str) -> HashMap<String, String> {
    let mut map = HashMap::new();
    let mut i = 0;
    let lines: Vec<&str> = text.lines().collect();
    while i < lines.len() {
        let line = lines[i].trim();
        if line.starts_with("msgid ") {
            let (msgid, next) = read_po_string(&lines, i);
            i = next;
            if msgid.is_empty() {
                continue;
            }
            if i < lines.len() && lines[i].trim().starts_with("msgstr ") {
                let (msgstr, next) = read_po_string(&lines, i);
                i = next;
                if !msgstr.is_empty() {
                    map.insert(msgid, msgstr);
                }
            }
            continue;
        }
        i += 1;
    }
    map
}

fn read_po_string(lines: &[&str], start: usize) -> (String, usize) {
    let first = lines[start].trim();
    let mut out = String::new();
    let mut i = start;
    let prefix = if first.starts_with("msgid ") {
        "msgid "
    } else if first.starts_with("msgstr ") {
        "msgstr "
    } else {
        return (String::new(), start + 1);
    };
    out.push_str(&parse_quoted_tail(first.strip_prefix(prefix).unwrap().trim()));
    i += 1;
    while i < lines.len() {
        let t = lines[i].trim();
        if t.starts_with('"') {
            out.push_str(&parse_quoted_line(t));
            i += 1;
        } else {
            break;
        }
    }
    (out, i)
}

fn parse_quoted_tail(s: &str) -> String {
    if s == "\"\"" {
        return String::new();
    }
    if s.starts_with('"') && s.ends_with('"') && s.len() >= 2 {
        return unescape_po(&s[1..s.len() - 1]);
    }
    String::new()
}

fn parse_quoted_line(s: &str) -> String {
    if s.starts_with('"') && s.ends_with('"') && s.len() >= 2 {
        unescape_po(&s[1..s.len() - 1])
    } else {
        String::new()
    }
}

fn unescape_po(s: &str) -> String {
    let mut out = String::new();
    let mut chars = s.chars().peekable();
    while let Some(c) = chars.next() {
        if c == '\\' {
            match chars.next() {
                Some('n') => out.push('\n'),
                Some('t') => out.push('\t'),
                Some('r') => out.push('\r'),
                Some('\\') => out.push('\\'),
                Some('"') => out.push('"'),
                Some(o) => {
                    out.push('\\');
                    out.push(o);
                }
                None => out.push('\\'),
            }
        } else {
            out.push(c);
        }
    }
    out
}
