CMsgPane::InformationSource CMsgPane::getInformationSourceFromUserGuidePath(const QString &path)
{
    // 0. 检查当前是否为FAQ问答
    if(path == "用户手册->FAQ问答") {
        return {"", "用户手册->FAQ问答", -2};
    }

    // 1. 检查路径前缀并记录匹配的前缀
    QString matchedPrefix;
    if (path.startsWith(userGuidePathPrefix)) {
        matchedPrefix = userGuidePathPrefix;
    } else if (path.startsWith(kaimingUserGuidePathPrefix)) {
        matchedPrefix = kaimingUserGuidePathPrefix;
    } else {
        return {"", "", -1}; // 两个前缀都不匹配
    }

    // 2. 检查路径前缀是否匹配
    if (path.length() <= matchedPrefix.length() ) {
        return {"", "", -1}; // 无效路径返回空对象
    }

    // 3. 截取前缀后的路径，提取appName
    QString tempPath = path.mid(matchedPrefix.length());
    int pos = tempPath.indexOf("/");
    if (pos == -1) {
        return {"", "", -1};
    }
    QString appName = tempPath.left(pos);

    // 4. 从映射表中查找对应的信息
    QMap<QString, InformationSource> sources = getInformationSources();
    if (sources.contains(appName)) {
        return sources[appName];
    }

    return {"", "", -1}; // 无匹配项返回空对象
}

void CMsgPane::onRecvMsg(const InnerMessage message)
{
    QString msg = message.msg;

    KyInfo() << "onRecvMsg" << msg << message.errorCode << message.is_end << message.index << message.reasoningContentMsg << message.model << message.is_reasoning_end << message.type << message.feedbackURL;

    //NLP错误码
    if(message.errorCode != 0)
    {
        //如果上一条消息正在显示，则调用停止回答接口
        if(recv_message != "")
        {
            clearStreamUiState();
            recv_message = "";
            recv_reasoning_message = "";

        }

        m_chatType = NORMAL;

        const bool gatewayError = (message.model == QLatin1String("Gateway"));

        //模型未配置，报错后结束会话。（网关错误保持原文，不参与 SDK 映射与「未配置模型」分支）
        if (!gatewayError && !checkChatModel(message.errorCode)) {
            return;
        }

        if (!gatewayError
            && static_cast<kyai::assistant::ErrorCode>(message.errorCode) != kyai::assistant::ErrorCode::UnknownError) {
            //对于未知错误，展示error_message字段对应的所有值   10000错误码显示sdk返回的报错信息
            msg = Globals::getErrorMsg(message.errorCode);
        }

        // 文本的网络错误和文生图的网络错误需要区分
        if (!gatewayError && message.type == "image_generation"
            && static_cast<kyai::assistant::ErrorCode>(message.errorCode) == kyai::assistant::ErrorCode::NetError) {
            msg = QObject::tr("The network connection is not available, please check the network settings and try again.");
        }

        if (gatewayError) {
            errorMessageToJs("", "ai", "red", msg);
        } else if (static_cast<kyai::assistant::ErrorCode>(message.errorCode) == kyai::assistant::ErrorCode::FreeAllocatedQuotaExceeded) {
            // 拼接红色异常提示和正常黑色提示文字
            msg = "<span style=\"color:red\">" + msg + "</span><br>" + tr("To ensure the normal use of Xiao K, please go to System Settings > AI Module Management > Model Configuration to configure the model.");
            errorMessageToJsNoModel("", "ai", "black", msg);
        } else if (static_cast<kyai::assistant::ErrorCode>(message.errorCode) == kyai::assistant::ErrorCode::LocalNlpModelNotLoaded) {
            // 拼接红色异常提示和正常黑色提示文字
            msg = "<span style=\"color:red\">" + msg + "</span>"+ "\n\n" + tr("Configuration steps:\n1. Go to the **System Settings > AI Module Management > Model Configuration** page to add a \"cloud model\", a \"local model\" or a \"optional model\".\n2. If the model configuration is already completed, please confirm whether the model is enabled.\n\nNote: Running a local model may consume significant device resources. Please ensure your device meets the performance requirements.");
            errorMessageToJsNoModel("", "ai", "black", msg);
        } else {
            errorMessageToJs("", "ai", "red", msg);
        }

        clearJsonMessage();
        return;
    }

    jsonObjToWeb["modelMsg"] = message.model;
    jsonObjToWeb["feedbackURL"] = message.feedbackURL;

    QJsonDocument aiJsonSendWebDoc(jsonObjToWeb);
    QString jsonMsgHeadToWeb = aiJsonSendWebDoc.toJson(QJsonDocument::Indented);
    // 如果是新消息的第一个回答，设置消息头，清空文本，准备显示正文
    if(new_reply){
        pushMsg("updateMsg", jsonMsgHeadToWeb, "");
        clearJsonMessage();
    }
    recv_message.append(msg);
    recv_reasoning_message.append(message.reasoningContentMsg);

    new_reply = message.is_end;
    m_is_reasoning_end = message.is_reasoning_end;

    if (message.is_end) {
        QString sessionId = QString::number(m_chat->getSession());
        Q_EMIT sessionReplyStatusChanged(sessionId, false, false);
    }

    updateBubble();
}

void CMsgPane::onRecvTaskMsg(const QString& sessionUuid, const InnerMessage message)
{
    QString msg = message.msg;

    // 助手端过滤掉部分已知不能渲染的符号
    msg = msg.replace("🔥","");
    msg = msg.replace("🏢","");
    msg = msg.replace("🤖","");

    KyInfo() << "onRecvTaskMsg msg===" << msg << message.type;

    TaskSession* session = m_taskSessionManager->getSession(sessionUuid);
    if (!session) {
        KyInfo() << "Received message for unknown session, ignoring:" << sessionUuid;
        return;
    }

    if (session->isCancelled) {
        if (!message.is_end) {
            KyInfo() << "Discarding message for cancelled session:" << sessionUuid;
            return;
        }
        session->isCancelled = false;
        KyInfo() << "Received end message for cancelled session, resetting:" << sessionUuid;
        return;
    }

    session->isReplying = !message.is_end;

    if (message.type == "tool_call" || message.type == "tool_result") {
        QJsonDocument toolDoc = QJsonDocument::fromJson(message.extraJson.toUtf8());
        KyInfo() << "toolDoc.object()==" << toolDoc.object();
        if (toolDoc.isObject()) {
            m_backendTaskToolCalls[sessionUuid].append(toolDoc.object());
        }
        if (sessionUuid == m_taskSessionManager->getActiveSessionUuid()) {
            if (new_reply) {
                jsonObjToWeb["modelMsg"] = modelMsgForTaskMode();
                QJsonDocument aiJsonSendWebDoc(jsonObjToWeb);
                QString jsonMsgHeadToWeb = aiJsonSendWebDoc.toJson(QJsonDocument::Indented);
                m_backendRecvMessageHeader[sessionUuid] = jsonMsgHeadToWeb;
                pushMsg("updateMsg", jsonMsgHeadToWeb, "");
                clearJsonMessage();
            }
            Q_EMIT updateTaskToolCalls(message.extraJson);
        }
        return;
    }

    if (sessionUuid == m_taskSessionManager->getActiveSessionUuid()) {
        if (message.errorCode != 0) {
            clearBackendRecvCache(sessionUuid);

            m_chatType = TASK_MODE;

            const bool gatewayNoModel = message.model == QLatin1String("Gateway")
                && message.errorCode == kGatewayInnerErrorNoModelConfigured;
            if (gatewayNoModel) {
                const QString friendly = tr("No available AI model detected. AI tasks cannot start. Please complete configuration in model management.");
                errorMessageToJsNoModel("", "ai", "red", friendly);
                clearJsonMessage();
                TaskSession* errorSession = m_taskSessionManager->getSession(sessionUuid);
                if (errorSession) {
                    Q_EMIT sessionReplyStatusChanged(QString::number(errorSession->historyId), false, false);
                }
                return;
            }

            if (message.model != QLatin1String("Gateway")) {
                msg = Globals::getErrorMsg(message.errorCode);
            }

            errorMessageToJs("", "ai", "red", msg);
            clearJsonMessage();
            TaskSession* errorSession = m_taskSessionManager->getSession(sessionUuid);
            if (errorSession) {
                Q_EMIT sessionReplyStatusChanged(QString::number(errorSession->historyId), false, false);
            }
            return;
        }

        jsonObjToWeb["modelMsg"] = modelMsgForTaskMode();
        jsonObjToWeb["feedbackURL"] = message.feedbackURL;

        QJsonDocument aiJsonSendWebDoc(jsonObjToWeb);
        QString jsonMsgHeadToWeb = aiJsonSendWebDoc.toJson(QJsonDocument::Indented);

        if (new_reply) {
            m_backendRecvMessageHeader[sessionUuid] = jsonMsgHeadToWeb;
            pushMsg("updateMsg", jsonMsgHeadToWeb, "");
            clearJsonMessage();
        }

        m_backendRecvMessage[sessionUuid].append(msg);
        m_backendRecvReasoningMsg[sessionUuid].append(message.reasoningContentMsg);

        new_reply = message.is_end;
        m_is_reasoning_end = message.is_reasoning_end;

        // 前端用 Text.MarkdownText 直接渲染，流式/结束都不再转 HTML
        if (!message.is_end) {
            if (message.reasoningContentMsg != "") {
            pushMsg("updateReasoningMsg", "", m_backendRecvReasoningMsg[sessionUuid], false);
            }
            if (msg != "") {
                pushMsg("updateMsg", "", m_backendRecvMessage[sessionUuid], false);
            }
        } else {
            // Ollama 等模型常常不发送流式 chunk，只在结束时返回一条 done 帧
            QString finalMsg = msg;
            if (finalMsg.isEmpty()) {
                finalMsg = m_backendRecvMessage.value(sessionUuid);
            } else {
                m_backendRecvMessage[sessionUuid] = finalMsg;
            }
            if (finalMsg != "") {
                pushMsg("updateMsg", "", finalMsg, false);
            } else {
                QJsonObject modelHeader;
                modelHeader["modelMsg"] = modelMsgForTaskMode();
                pushMsg("updateMsg", QJsonDocument(modelHeader).toJson(QJsonDocument::Compact), "");
            }
            pushMsg("replyEnd", true);
            clearBackendRecvCache(sessionUuid);
            TaskSession* endSession = m_taskSessionManager->getSession(sessionUuid);
            if (endSession) {
                Q_EMIT sessionReplyStatusChanged(QString::number(endSession->historyId), false, false);
            }
        }
    } else {
        if (!m_backendRecvMessage.contains(sessionUuid)) {
            QJsonObject header;
            header["modelMsg"] = modelMsgForTaskMode();
            header["feedbackURL"] = message.feedbackURL;
            m_backendRecvMessageHeader[sessionUuid] = QJsonDocument(header).toJson(QJsonDocument::Compact);
        }
        // 由于最后一条消息会返回所有消息内容，所以最后一条消息不保存
        if (!message.is_end) {
            m_backendRecvMessage[sessionUuid].append(msg);
            m_backendRecvReasoningMsg[sessionUuid].append(message.reasoningContentMsg);
        } else {
            {
                QString notifyMsg = msg;
                notifyMsg.replace(QRegularExpression("```[\\s\\S]*?```"), "");
                notifyMsg.replace(QRegularExpression("`([^`]+)`"), "\\1");
                notifyMsg.replace(QRegularExpression("!\\[([^\\]]*)\\]\\([^\\)]*\\)"), "\\1");
                notifyMsg.replace(QRegularExpression("\\[([^\\]]+)\\]\\([^\\)]*\\)"), "\\1");
                notifyMsg.replace(QRegularExpression("(?m)^\\s{0,3}(#{1,6})\\s+"), "");
                notifyMsg.replace(QRegularExpression("(?m)^\\s{0,3}[-*_]{3,}\\s*$"), "");
                notifyMsg.replace(QRegularExpression("(?m)^\\s{0,3}[-*+]\\s+"), "");
                notifyMsg.replace(QRegularExpression("(?m)^\\s*\\d+\\.\\s+"), "");
                notifyMsg.replace(QRegularExpression("\\*\\*([^*]+)\\*\\*"), "\\1");
                notifyMsg.replace(QRegularExpression("__([^_]+)__"), "\\1");
                notifyMsg.replace(QRegularExpression("\\*([^*]+)\\*"), "\\1");
                notifyMsg.replace(QRegularExpression("_([^_]+)_"), "\\1");
                notifyMsg.replace(QRegularExpression("~~([^~]+)~~"), "\\1");
                notifyMsg.replace(QRegularExpression("[\\r\\n]+"), " ");
                notifyMsg = notifyMsg.simplified();
                if (notifyMsg.length() > 100){
                    notifyMsg = notifyMsg.left(100);
                }
                KyInfo() << "notifyMsg=====" << notifyMsg;
                NotificationNotify::getInstance()->sendNotification(QObject::tr("Agent"), notifyMsg, QString::number(session->historyId));
            }
            QString finalMsg = msg.isEmpty() ? m_backendRecvMessage.value(sessionUuid) : msg;
            const QString historyIdStr = QString::number(session->historyId);
            saveBackendMessageToDatabase(sessionUuid, finalMsg, message);
            clearBackendRecvCache(sessionUuid);
            m_database->setUnreadFlag(historyIdStr, 1);
            Q_EMIT sessionReplyStatusChanged(historyIdStr, false, true);
            Q_EMIT scheduledSessionCreated(historyIdStr);
            if (sessionUuid != m_taskSessionManager->getActiveSessionUuid()) {
                m_taskSessionManager->closeSession(sessionUuid);
            }
        }
    }
}

