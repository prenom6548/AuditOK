void CMsgPane::deleteSessionList(const QVariantList &strings)
{
    // 删除选中历史记录
    // 用户点击了取消按钮或关闭了消息框，执行取消操作
    //KyInfo() << "deleteSessionList";
    QStringList deleteList;
    for (const QVariant &sessionIDs : strings) {
        QString sessionID = sessionIDs.toString();
        KyInfo() << "删除的sessionID为:" << sessionID;
        if(sessionID == QString::number(m_chat->getSession())){
            // stopreply之后不会触发自动朗读
            m_chat->soundFlag = false;
            onStopReply();
            Q_EMIT VoiceUsingManager::getInstance()->sigInterruptUsing(false);

            Q_EMIT clearListModel();

            QTimer *tempTimer = new QTimer();
            connect(tempTimer,&QTimer::timeout,[&]{
                m_chat->clearContext();
                m_chat->setSession(getCurrentMaxHistoryId());
                Q_EMIT changeSessionId(m_chat->getSession());
            });
            tempTimer->setSingleShot(true);
            tempTimer->start(1000);
        }
        // 任务会话清理：通过数据库modeType判断是否为任务模式会话，
        // 先关闭本地TaskSession和清理缓存，再通知后端删除会话数据
        if (m_taskSessionManager) {
            int modeType = m_database->getSessionModeType(sessionID);
            if (modeType == 1) {
                QString sessionUuid = m_database->selectSessionUuidBySessionID(sessionID);

                bool isCurrentlyActive = (sessionID == QString::number(m_chat->getSession()));
                if (isCurrentlyActive) {
                    QString activeUuid = m_taskSessionManager->getActiveSessionUuid();
                    if (!activeUuid.isEmpty()) {
                        m_taskSessionManager->cancelResponse(activeUuid);
                        clearBackendRecvCache(activeUuid);
                        m_taskSessionManager->closeSession(activeUuid);
                    }
                    m_chatType = NORMAL;
                } else {
                    TaskSession* taskSession = m_taskSessionManager->getSessionByHistoryId(sessionID.toInt());
                    if (taskSession) {
                        m_taskSessionManager->cancelResponse(taskSession->sessionUuid);
                        clearBackendRecvCache(taskSession->sessionUuid);
                        m_taskSessionManager->closeSession(taskSession->sessionUuid);
                        Q_EMIT sessionReplyStatusChanged(sessionID, false, false);
                    }
                }

                m_taskSessionManager->deleteBackendSession(sessionUuid);
            }
        }

        m_database->deleteBySessionID(sessionID);
        // 同时删除对应的文件引用记录
        DocumentReferenceDatabase::getInstance()->deleteDocumentReferenceBySessionID(sessionID);
        deleteList.append(sessionID);
    }
    //调用前端页面删除
    Q_EMIT deleteDialogueList(deleteList);
}

