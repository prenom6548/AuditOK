// 过滤掉带圈数字角标的辅助函数
static QString filterChunkIndex(const QString &text)
{
    QString filteredText = text;
    // 使用 QChar 范围匹配，移除 ❶❷❸...➉ 这些角标字符（Unicode 0x2776-0x2789）
    for (int i = text.length() - 1; i >= 0; --i) {
        ushort unicode = text.at(i).unicode();
        if (unicode >= 0x2460 && unicode <= 0x2470) {
            filteredText.remove(i, 1);
        }
    }
    return filteredText;
}

