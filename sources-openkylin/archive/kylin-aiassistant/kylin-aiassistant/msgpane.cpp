/** Markdown 转 HTML 前的标题规范化：
 *  - 模型偶发输出 7+ 个 #（如 ########），CommonMark 仅支持 1–6 级，多余 # 会原样显示；
 *  - 原全局 replace("#","##") 会把每个 # 倍增，导致 ## 变 ####、######## 变 16 个 #。
 *  做法：超长行首 ATX 压成 ##；仅「单独 # + 空白」的一级标题降为二级。
 */
QString normalizeAtxHeadingsForDisplay(QString msg)
{
    static const QRegularExpression longHeadingPattern(
        QStringLiteral(R"(^(\s{0,3})#{7,}(\s+))"),
        QRegularExpression::MultilineOption);
    msg.replace(longHeadingPattern, QStringLiteral("\\1##\\2"));

    static const QRegularExpression h1ToH2Pattern(
        QStringLiteral(R"(^(\s{0,3})#(?![#])(\s+))"),
        QRegularExpression::MultilineOption);
    msg.replace(h1ToH2Pattern, QStringLiteral("\\1##\\2"));
    return msg;
}

/** cmark 围栏代码块输出 <pre><code>…</code></pre>；Qt 富文本中 <pre> 默认不换行，长行会从右侧裁切。
 *  为未带 style 的 <pre …> 注入 pre-wrap，使代码在气泡宽度内折行显示。
 */
QString ensureCodeBlockPreTagsWrap(const QString &html)
{
    if (html.isEmpty()) {
        return html;
    }
    QString out = html;
    static const QRegularExpression preOpen(
        QStringLiteral(R"(<pre(?![^>]*\bstyle\s*=)([^>]*)>)"),
        QRegularExpression::CaseInsensitiveOption);
    out.replace(preOpen, QStringLiteral(R"(<pre style="white-space:pre-wrap;word-wrap:break-word"\1>)"));
    return out;
}

