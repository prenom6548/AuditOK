void CMsgPane::getDialogueList()
{
    QStringList list = m_database->selectAllDialogue();

    QString activeNormalSessionId;
    bool nonTaskChatReplying = false;
    if (m_isReplying && m_chatType != TASK_MODE && m_chat) {
        int sid = m_chat->getSession();
        if (sid > 0) {
            activeNormalSessionId = QString::number(sid);
            nonTaskChatReplying = true;
        }
    }

    for (int i = 0; i < list.size(); ++i) {
        QJsonDocument doc = QJsonDocument::fromJson(list[i].toUtf8());
        if (!doc.isObject()) continue;
        QJsonObject obj = doc.object();
        int modeType = obj.value("modeType").toInt(0);

        if (modeType == 1) {
            if (m_taskSessionManager) {
                QString sessionID = obj.value("sessionID").toString();
                TaskSession* session = m_taskSessionManager->getSessionByHistoryId(sessionID.toInt());
                if (session && session->isReplying) {
                    obj["isReplying"] = true;
                    list[i] = QJsonDocument(obj).toJson(QJsonDocument::Compact);
                }
            }
        } else {
            if (nonTaskChatReplying) {
                QString sessionID = obj.value("sessionID").toString();
                if (sessionID == activeNormalSessionId) {
                    obj["isReplying"] = true;
                    list[i] = QJsonDocument(obj).toJson(QJsonDocument::Compact);
                }
            }
        }
    }

    Q_EMIT loadDialogueList(list);
}

