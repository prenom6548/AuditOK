// ============================================================================
// kybot cron 历史同步：把 KylinBot 的 cron 运行结果导入为本地 task-mode 历史
// 详见 scheduled/kybotcronsyncmanager.* 与计划 kybot-cron-history-sync
// ============================================================================

struct ParsedKybotCronRunOutput {
    QString message;
    QString thinking;
    QJsonArray toolCalls;
};

static bool parseLooseJsonStringAt(const QString& text, int quotePos, QString& out)
{
    if (quotePos < 0 || quotePos >= text.size() || text.at(quotePos) != QLatin1Char('"')) {
        return false;
    }

    QString decoded;
    decoded.reserve(text.size() - quotePos);

    for (int i = quotePos + 1; i < text.size(); ++i) {
        const QChar ch = text.at(i);
        if (ch == QLatin1Char('"')) {
            out = decoded;
            return true;
        }
        if (ch != QLatin1Char('\\')) {
            decoded.append(ch);
            continue;
        }

        ++i;
        if (i >= text.size()) {
            return false;
        }

        const QChar esc = text.at(i);
        switch (esc.unicode()) {
        case '"':
            decoded.append(QLatin1Char('"'));
            break;
        case '\\':
            decoded.append(QLatin1Char('\\'));
            break;
        case '/':
            decoded.append(QLatin1Char('/'));
            break;
        case 'b':
            decoded.append(QLatin1Char('\b'));
            break;
        case 'f':
            decoded.append(QLatin1Char('\f'));
            break;
        case 'n':
            decoded.append(QLatin1Char('\n'));
            break;
        case 'r':
            decoded.append(QLatin1Char('\r'));
            break;
        case 't':
            decoded.append(QLatin1Char('\t'));
            break;
        case 'u': {
            if (i + 4 >= text.size()) {
                return false;
            }
            bool ok = false;
            const ushort code = text.mid(i + 1, 4).toUShort(&ok, 16);
            if (!ok) {
                return false;
            }
            decoded.append(QChar(code));
            i += 4;
            break;
        }
        default:
            decoded.append(esc);
            break;
        }
    }

    return false;
}

static QString extractLooseJsonStringField(const QString& text,
                                           const QString& fieldName,
                                           int searchStart = 0)
{
    const QString marker = QStringLiteral("\"%1\"").arg(fieldName);
    int fieldPos = text.indexOf(marker, searchStart);
    while (fieldPos >= 0) {
        const int colonPos = text.indexOf(QLatin1Char(':'), fieldPos + marker.size());
        if (colonPos < 0) {
            return QString();
        }

        int valuePos = colonPos + 1;
        while (valuePos < text.size() && text.at(valuePos).isSpace()) {
            ++valuePos;
        }

        if (valuePos < text.size() && text.at(valuePos) == QLatin1Char('"')) {
            QString value;
            if (parseLooseJsonStringAt(text, valuePos, value)) {
                return value;
            }
            return QString();
        }

        fieldPos = text.indexOf(marker, fieldPos + marker.size());
    }

    return QString();
}

