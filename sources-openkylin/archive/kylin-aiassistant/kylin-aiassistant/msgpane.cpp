bool CMsgPane::importKybotCronRun(const QString& jobId,
                                  const QString& jobName,
                                  const QString& jobPrompt,
                                  const QString& runId,
                                  const QString& runOutput,
                                  const QString& runStatus,
                                  qint64 startedAtSecs)
{
    if (!m_database) {
        return false;
    }
    if (runId.isEmpty()) {
        return false;
    }

    const QString sessionID = QStringLiteral("kybot-cron:%1").arg(runId);
    if (m_database->sessionExists(sessionID)) {
        return false;
    }

    const QString userJson = buildKybotCronUserMessageJson(jobId, jobName, jobPrompt, runId);

    const ParsedKybotCronRunOutput parsedOutput = parseKybotCronRunOutput(runOutput);
    QString taskToolCallsJson;
    if (!parsedOutput.toolCalls.isEmpty()) {
        QJsonObject toolCallsObj;
        toolCallsObj["toolCalls"] = parsedOutput.toolCalls;
        taskToolCallsJson = QString::fromUtf8(
            QJsonDocument(toolCallsObj).toJson(QJsonDocument::Compact));
    }
    const QString botJson = buildKybotCronBotMessageJson(
        parsedOutput.message, runStatus, parsedOutput.thinking, taskToolCallsJson);

    // 两条 RECORD 行：msgIndex=0 为 user prompt，msgIndex=1 为 bot output
    // mode_type=1 复用 task mode 展示，chat_type=0
    if (!m_database->insertOneWithModeType(sessionID, 0, userJson, 0, 1)) {
        KyInfo() << "importKybotCronRun: failed to insert user row, sessionID=" << sessionID;
        return false;
    }
    if (!m_database->insertOneWithModeType(sessionID, 1, botJson, 0, 1)) {
        KyInfo() << "importKybotCronRun: failed to insert bot row, sessionID=" << sessionID;
        // 回滚 user 行避免半截会话
        m_database->deleteBySessionID(sessionID);
        return false;
    }

    if (startedAtSecs > 0) {
        m_database->setOperateTime(sessionID, 0, startedAtSecs);
        m_database->setOperateTime(sessionID, 1, startedAtSecs);
    }

    m_database->setUnreadFlag(sessionID, 1);
    m_database->markSessionSource(sessionID,
        QStringLiteral("scheduler:kybot:%1:%2").arg(jobId, runId));

    KyInfo() << "importKybotCronRun: inserted" << sessionID
             << "job=" << jobName << "status=" << runStatus;
    return true;
}

