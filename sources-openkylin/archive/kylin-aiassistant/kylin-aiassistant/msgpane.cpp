QString expandHomePath(QString path)
{
    path = path.trimmed();
    if (path.startsWith(QStringLiteral("~/"))) {
        return QDir::homePath() + path.mid(1);
    }
    if (path == QStringLiteral("~")) {
        return QDir::homePath();
    }
    return path;
}

// 将 file:// 或相对路径转为本地绝对路径，供智能体文档上传/网关 [DOCUMENT] 使用
QString toAbsoluteLocalFilePath(const QString &pathOrUrl)
{
    QString local = expandHomePath(pathOrUrl);
    if (local.startsWith(QLatin1String("file:"), Qt::CaseInsensitive)) {
        local = QUrl(local).toLocalFile();
    }
    if (local.isEmpty()) {
        return local;
    }
    QFileInfo fi(local);
    const QString canonical = fi.canonicalFilePath();
    return canonical.isEmpty() ? fi.absoluteFilePath() : canonical;
}

