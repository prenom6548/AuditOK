UnixHttpResponse requestGatewayViaHttp(const QString &method,
                                       const QString &path,
                                       const QMap<QString, QString> &headers = QMap<QString, QString>(),
                                       const QByteArray &body = QByteArray())
{
    UnixHttpResponse resp;
    QNetworkAccessManager mgr;
    QNetworkRequest req;
    req.setUrl(QUrl(QStringLiteral("http://") + configuredGatewayHost() + path));
    req.setHeader(QNetworkRequest::ContentTypeHeader, QStringLiteral("application/json"));
    for (auto it = headers.constBegin(); it != headers.constEnd(); ++it) {
        req.setRawHeader(it.key().toUtf8(), it.value().toUtf8());
    }

    QNetworkReply *reply = nullptr;
    if (method == QStringLiteral("GET")) {
        reply = mgr.get(req);
    } else if (method == QStringLiteral("POST")) {
        reply = mgr.post(req, body);
    } else if (method == QStringLiteral("DELETE")) {
        reply = mgr.deleteResource(req);
    } else {
        resp.errorString = QStringLiteral("Unsupported HTTP method: %1").arg(method);
        return resp;
    }

    QEventLoop loop;
    QObject::connect(reply, &QNetworkReply::finished, &loop, &QEventLoop::quit);
    loop.exec();

    resp.statusCode = reply->attribute(QNetworkRequest::HttpStatusCodeAttribute).toInt();
    resp.body = reply->readAll();
    if (reply->error() != QNetworkReply::NoError) {
        resp.errorString = reply->errorString();
    }
    reply->deleteLater();
    return resp;
}

UnixHttpResponse requestGatewayViaSocket(const QString &method,
                                         const QString &path,
                                         const QMap<QString, QString> &headers = QMap<QString, QString>(),
                                         const QByteArray &body = QByteArray())
{
    UnixSocketWebSocket client;
    configureGatewaySocket(client);
    if (method == QStringLiteral("GET")) {
        return client.httpGet(path, headers);
    }
    if (method == QStringLiteral("POST")) {
        return client.httpPost(path, body, headers);
    }
    if (method == QStringLiteral("DELETE")) {
        return client.httpDelete(path, headers);
    }

    UnixHttpResponse resp;
    resp.errorString = QStringLiteral("Unsupported HTTP method: %1").arg(method);
    return resp;
}

UnixHttpResponse requestGatewaySocketFirst(const QString &method,
                                           const QString &path,
                                           const QMap<QString, QString> &headers = QMap<QString, QString>(),
                                           const QByteArray &body = QByteArray())
{
    UnixHttpResponse resp = requestGatewayViaSocket(method, path, headers, body);
    if (resp.statusCode != 0) {
        return resp;
    }

    KyInfo() << "Gateway Unix socket request failed, fallback to HTTP:"
             << method << path << resp.errorString;
    return requestGatewayViaHttp(method, path, headers, body);
}

QString cleanBase64Whitespace(QString base64)
{
    base64.remove(QLatin1Char('\r'));
    base64.remove(QLatin1Char('\n'));
    base64.remove(QLatin1Char(' '));
    return base64;
}

QString mimeTypeFromImagePath(const QString &imagePath)
{
    const QString s = imagePath.toLower();
    if (s.endsWith(QLatin1String(".png")))
        return QStringLiteral("image/png");
    if (s.endsWith(QLatin1String(".jpg")) || s.endsWith(QLatin1String(".jpeg"))
        || s.endsWith(QLatin1String(".jpe")))
        return QStringLiteral("image/jpeg");
    if (s.endsWith(QLatin1String(".webp")))
        return QStringLiteral("image/webp");
    if (s.endsWith(QLatin1String(".gif")))
        return QStringLiteral("image/gif");
    if (s.endsWith(QLatin1String(".bmp")))
        return QStringLiteral("image/bmp");
    return QStringLiteral("image/png");
}

// 与 voice-assistant GatewayChatClient::encodeContentWithScreenshotImage 中 data URI 规则一致，再包一层 [IMAGE:...]；供任务模式发给网关。
QString taskModeImageDataUri(const QString &imageSrc, const QString &imagePath)
{
    const QString trimmed = imageSrc.trimmed();
    if (trimmed.isEmpty())
        return QString();

    if (trimmed.startsWith(QLatin1String("data:image/"), Qt::CaseInsensitive)) {
        const int comma = trimmed.indexOf(QLatin1Char(','));
        if (comma <= 0)
            return trimmed;
        const QString header = trimmed.left(comma);
        QString payload = cleanBase64Whitespace(trimmed.mid(comma + 1));
        if (payload.isEmpty())
            return QString();
        return header + QLatin1Char(',') + payload;
    }

    const QString payload = cleanBase64Whitespace(trimmed);
    if (payload.isEmpty())
        return QString();
    return QStringLiteral("data:%1;base64,").arg(mimeTypeFromImagePath(imagePath)) + payload;
}

QString prependTaskModeImageForGateway(const QString &userText, const QString &imageSrc, const QString &imagePath)
{
    const QString dataUri = taskModeImageDataUri(imageSrc, imagePath);
    if (dataUri.isEmpty())
        return userText;
    // 标记置于用户输入之前，两段之间两个换行（与产品约定、voice-assistant [IMAGE:...] 格式一致）
    const QString marker = QStringLiteral("[IMAGE:") + dataUri + QLatin1Char(']');
    return marker + QStringLiteral("\n\n") + userText;
}

// 任务模式：上传的文档在用户输入前增加 [DOCUMENT] 块，与用户原文之间两个换行
QString prependTaskModeDocumentsForGateway(const QString &userText, const QList<DocumentInfo> &documents)
{
    if (documents.isEmpty())
        return userText;

    QString blocks;
    for (const DocumentInfo &doc : documents) {
        const QString name = doc.documentName.trimmed();
        const QString path = toAbsoluteLocalFilePath(doc.documentPath);
        if (name.isEmpty() && path.isEmpty())
            continue;
        if (!blocks.isEmpty())
            blocks += QLatin1Char('\n');
        blocks += QStringLiteral("[DOCUMENT]\n  name=%1\n  path=%2\n  [/DOCUMENT]")
                        .arg(name, path);
    }
    if (blocks.isEmpty())
        return userText;
    return blocks + QStringLiteral("\n\n") + userText;
}

