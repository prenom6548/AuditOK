QString iconToBase64(const QIcon &icon)
{
    // 将QIcon转换为QPixmap（使用默认大小或指定大小）
    QPixmap pixmap = icon.pixmap(32, 32); // 例如，32x32像素大小
    QByteArray ba;
    QBuffer buffer(&ba);
    buffer.open(QIODevice::WriteOnly);

    // 将QPixmap保存为字节数组
    pixmap.save(&buffer, "PNG"); // 使用PNG格式保存
    buffer.close();

    // 对字节数组进行Base64编码
    QString base64 = ba.toBase64();

    return base64;
}
void CMsgPane::onShowDocument(const QString &filePath)
{
    const QString absolutePath = toAbsoluteLocalFilePath(filePath);
    //传入文件路径，文件图标，文件名，文件大小
    QFileInfo fileInfo(absolutePath);
    if(!fileInfo.exists())
    {
        KyInfo() << "文件不存在:" << absolutePath;
        return;
    }

    QString fileName = fileInfo.fileName();

    // 获取图标 - 使用与知识库管理一致的图标路径
    QString str = Globals::getFileIconPath(absolutePath);

    qint64 size = fileInfo.size();
    double fileSizeKB = static_cast<double>(size) / 1024;
    // 上传文件大小不能超过50MB
    if(fileSizeKB > 50 * 1024){
        if (m_isReplying) {
            onStopReply();
        }
        QTimer::singleShot(100, this, [=]{
            QJsonObject jsonObj;
            jsonObj["msgHead"] = msgHead;
            jsonObj["promptId"] = -1;
            jsonObj["promptIconPath"] = "";
            jsonObj["modelMsg"] = "ai";
            jsonObj["colorMsg"] = "red";
            jsonObj["imageSrc"] = "";
            QJsonDocument ModelJsonSendWebDoc(jsonObj);
            QString errorJsonMsgHeadToWeb = ModelJsonSendWebDoc.toJson(QJsonDocument::Indented);
            pushMsg("addRecvMsg", errorJsonMsgHeadToWeb, tr("The size of the uploaded file cannot exceed 50MB."));
            pushMsg("replyEnd", true);
            clearJsonMessage();
        });
        return;
    }
    QString fileSize;
    if(fileSizeKB > 1024)
    {
        double fileSizeMB = static_cast<double>(fileSizeKB) / 1024;
        fileSize = QString::number(fileSizeMB, 'f', 2) + "MB";
    }
    else
    {
        fileSize = QString::number(fileSizeKB, 'f', 2) + "KB";
    }
    activateMainWindow();
    Q_EMIT addDocumentPreview(absolutePath, str, fileName, fileSize);
}

