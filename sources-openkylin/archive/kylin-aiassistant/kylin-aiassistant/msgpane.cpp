//消息类发送接口，所有对话类消息通过此处发送至前端
void CMsgPane::pushMsg(QString func, QString jsonMsgHeadToWeb, QString msg, bool convertMarkdown)
{
    QString markdownMsg = msg;
    if (func == "addMsg") {
        Q_EMIT addMsg(jsonMsgHeadToWeb, msg);
    }

    // 若内容已被识别为「HTML」，则不再做 Markdown→HTML，避免重复包裹。
    // 注意：不能用任意「<...>」判断——文档/命令里的占位符（如 <本地用户名>）、
    // 不等式片段等会误匹配，导致跳过 convertMarkDownToHtml，界面出现「Markdown 平铺」。
    static const QRegularExpression preRenderedHtmlTagPattern(
        QStringLiteral(R"(<\s*/?(?:p|div|span|br|hr|h[1-6]|ul|ol|li|table|tr|td|th|thead|tbody|tfoot|caption|colgroup|col|a|strong|em|b|i|u|pre|code|blockquote|section|article|nav|header|footer|main|aside|dl|dt|dd|img|figure|figcaption|svg|video|audio|source|canvas|body|html|head|meta|link|style|script|title|form|input|button|label|select|option|textarea|font|center|small|sub|sup)\b)"),
        QRegularExpression::CaseInsensitiveOption);
    QRegularExpressionMatch match = preRenderedHtmlTagPattern.match(msg);
    // 聊天气泡由 QML Text.MarkdownText 直接渲染，后端不再 cmark 转 HTML。
    // 仅规范化超长 ATX 标题（# 超过 6 个时 Qt/CommonMark 会原样显示）。
    Q_UNUSED(convertMarkdown);
    if (msg != "" && !match.hasMatch()) {
        msg = normalizeAtxHeadingsForDisplay(msg);
        markdownMsg = msg;
    }


    // KyInfo() << "msg" << msg;

    if (func == "addRecvMsg") {
        Q_EMIT addRecvMsg(jsonMsgHeadToWeb, msg);
    }

    if (func == "updateMsg") {
        Q_EMIT updateMsg(jsonMsgHeadToWeb, msg, markdownMsg);
    }
    if(func == "addRecvSources"){
        Q_EMIT addRecvSources(jsonMsgHeadToWeb);
    }
    if(func == "appendRecvTool"){
        Q_EMIT appendRecvTool(jsonMsgHeadToWeb);
    }
    if (func == "updateReasoningMsg") {
        Q_EMIT updateReasoningMsg(jsonMsgHeadToWeb, msg);
    }
}

