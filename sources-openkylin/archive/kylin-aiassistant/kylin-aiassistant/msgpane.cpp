///
/// \brief CMsgPane::checkChatModel  用于检查NLP模型、VISION模型、意图模型（本地NLP模型）是否配置
/// \param errorCode   错误码
/// \return 如果对应模型配置了，返回true；反之，返回false
///
bool CMsgPane::checkChatModel(int errorCode)
{
    kyai::assistant::ErrorCode error = static_cast<kyai::assistant::ErrorCode>(errorCode);
    if (error == kyai::assistant::ErrorCode::NlpModelNotFound || error == kyai::assistant::ErrorCode::VisionModelNotFound || error == kyai::assistant::ErrorCode::IntentNlpModelNotFound) {
        QJsonObject errorObject;
        errorObject["modelMsg"] = "ai";
        errorObject["noModelError"] = "true";
        QJsonDocument errorDoc(errorObject);
        QString json = errorDoc.toJson(QJsonDocument::Indented);
        QString errorMsg = "";

        switch(error){
        case kyai::assistant::ErrorCode::NlpModelNotFound:
            errorMsg = tr("<span style=\"color:red\">There are currently no available large language model available.</span> <br><br> Configuration steps: <br> 1. Go to the <strong>System Settings &gt; AI Module Management &gt; Model Configuration</strong> page to add a \"cloud model\", a \"local model\" or a \"optional model\". <br> 2. If the model configuration is already completed, please confirm whether the model is enabled. <br><br> Note: Running a local model may consume significant device resources. Please ensure your device meets the performance requirements.");
            break;
        case  kyai::assistant::ErrorCode::VisionModelNotFound:
            errorMsg = tr("<span style=\"color:red\">There are currently no available vision model available.</span> <br><br> Configuration steps: <br> 1. Go to the <strong>System Settings &gt; AI Module Management &gt; Model Configuration</strong> page to add a \"cloud model\", a \"local model\" or a \"optional model\". <br> 2. If the model configuration is already completed, please confirm whether the model is enabled. <br><br> Note: Running a local model may consume significant device resources. Please ensure your device meets the performance requirements.");
            break;
        case  kyai::assistant::ErrorCode::IntentNlpModelNotFound:
            errorMsg = tr("<span style=\"color:red\">There are currently no available large language model available.</span> <br><br> Configuration steps: <br> 1. Go to the <strong>System Settings &gt; AI Module Management &gt; Model Configuration</strong> page to add a \"cloud model\", a \"local model\" or a \"optional model\". <br> 2. If the model configuration is already completed, please confirm whether the model is enabled. <br><br> Note: Running a local model may consume significant device resources. Please ensure your device meets the performance requirements.");
            break;
        }

        pushMsg("updateMsg", json, errorMsg);

        QTimer *tempTimer = new QTimer(this);
        connect(tempTimer,&QTimer::timeout,this,[&]{
            pushMsg("replyEnd", true);
        });
        tempTimer->setSingleShot(true);
        tempTimer->start(1000);

        return false;
    }


    return true;
}

