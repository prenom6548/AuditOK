static QStringList filterVoiceMessagesFromTextHistory(const QStringList &list)
{
    QStringList filtered;
    filtered.reserve(list.size());
    for (const QString &item : list) {
        QJsonParseError jsonErr;
        const QJsonDocument jsonDoc = QJsonDocument::fromJson(item.toUtf8(), &jsonErr);
        if (jsonErr.error == QJsonParseError::NoError && jsonDoc.isObject()
                && isVoiceAssistantStoredMessage(jsonDoc.object())) {
            continue;
        }
        filtered.append(item);
    }
    return filtered;
}

static bool isVoiceBotErrorMessage(const QJsonObject &obj)
{
    const bool sentByUser = obj.value(QStringLiteral("sentByUser")).toBool(false);
    const QString author = obj.value(QStringLiteral("author")).toString();
    const bool isBot = author == QLatin1String("Bot") || (!obj.contains(QStringLiteral("author")) && !sentByUser);
    return isBot
            && obj.value(QStringLiteral("colorMsg")).toString() == QLatin1String("red")
            && !obj.value(QStringLiteral("message")).toString().trimmed().isEmpty();
}

static QStringList dedupeConsecutiveVoiceErrorMessages(const QStringList &list)
{
    QStringList deduped;
    deduped.reserve(list.size());
    QString lastBotErrorKey;
    for (const QString &item : list) {
        QJsonParseError jsonErr;
        const QJsonDocument jsonDoc = QJsonDocument::fromJson(item.toUtf8(), &jsonErr);
        if (jsonErr.error == QJsonParseError::NoError && jsonDoc.isObject()) {
            const QJsonObject obj = jsonDoc.object();
            if (isVoiceBotErrorMessage(obj)) {
                const QString key = obj.value(QStringLiteral("message")).toString().trimmed();
                if (key == lastBotErrorKey) {
                    continue;
                }
                lastBotErrorKey = key;
            } else {
                lastBotErrorKey.clear();
            }
        }
        deduped.append(item);
    }
    return deduped;
}

static std::vector<Message> buildVoiceAssistantChatHistoryFromConversationList(const QStringList &list)
{
    std::vector<Message> history;
    for (const QString &jsonStr : list) {
        QJsonDocument jsonDoc = QJsonDocument::fromJson(jsonStr.toUtf8());
        if (!jsonDoc.isObject()) {
            continue;
        }
        QJsonObject jsonObj = jsonDoc.object();
        QString author = jsonObj.value(QStringLiteral("author")).toString();
        if (author.isEmpty()) {
            author = jsonObj.value(QStringLiteral("sentByUser")).toBool(false)
                    ? QStringLiteral("User") : QStringLiteral("Bot");
        }
        const std::string msg = removeHtmlTags(jsonObj.value(QStringLiteral("message")).toString()).toStdString();
        if (msg.empty()) {
            continue;
        }
        Message m;
        if (author == QLatin1String("User")) {
            m.user = msg;
        } else {
            m.assistant = msg;
        }
        history.push_back(m);
    }
    return history;
}

