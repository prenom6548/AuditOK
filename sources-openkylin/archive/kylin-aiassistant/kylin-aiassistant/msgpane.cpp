void CMsgPane::onCopyImage(const QString &base64Image)
{
    if (m_copyImageToClipboardInProgress) {
        KyInfo() << "copy image already in progress, ignore duplicate request";
        return;
    }
    if (base64Image.isEmpty()) {
        return;
    }

    m_copyImageToClipboardInProgress = true;

    // 由于 base64 解码 + QImage::loadFromData 进行“像素解码/加载”可能很耗时，
    // 这里改为：后台只把 base64 解码成“原始图片字节”，主线程仅设置剪贴板 mimeData。
    auto *watcher = new QFutureWatcher<ClipboardImagePayload>(this);
    connect(watcher, &QFutureWatcher<ClipboardImagePayload>::finished, this, [this, watcher]() {
        ClipboardImagePayload payload = watcher->result();
        watcher->deleteLater();
        m_copyImageToClipboardInProgress = false;

        if (payload.data.isEmpty() || payload.mimeType.isEmpty()) {
            KyInfo() << "copy image: decode to bytes failed";
            return;
        }

        // 复制到剪切板（主线程执行）
        // 说明：setMimeData 可能仍涉及与剪贴板管理器交互；延后到下一轮事件循环，减少抢占 UI 绘制。
        QTimer::singleShot(0, this, [this, payload]() mutable {
            QClipboard *clipBoard = QApplication::clipboard();
            QMimeData *mimeData = new QMimeData();
            mimeData->setData(payload.mimeType, payload.data);
            clipBoard->setMimeData(mimeData, QClipboard::Clipboard);
            KyInfo() << "复制图片到剪贴板";
            Q_EMIT copyImageToClipboard();
        });
    });

    auto future = QtConcurrent::run([base64Image]() -> ClipboardImagePayload {
        ClipboardImagePayload payload;
        int commaIndex = base64Image.indexOf(',');
        if (commaIndex == -1) {
            return payload;
        }

        // 解析 mime type：data:image/png;base64,xxxxx
        // 兜底：如果解析失败，默认 image/png。
        int prefixStart = base64Image.indexOf("data:");
        if (prefixStart == 0) {
            int mimeEnd = base64Image.indexOf(';', prefixStart + 5);
            if (mimeEnd > prefixStart + 5) {
                payload.mimeType = base64Image.mid(prefixStart + 5, mimeEnd - (prefixStart + 5)).trimmed();
            }
        }
        if (payload.mimeType.isEmpty()) {
            payload.mimeType = QStringLiteral("image/png");
        }

        // 去掉 data:image/*;base64, 前缀部分，仅解码 base64 payload 为原始图片字节。
        QByteArray decodedData = QByteArray::fromBase64(base64Image.mid(commaIndex + 1).toUtf8());
        payload.data = decodedData;
        return payload;
    });
    watcher->setFuture(future);

}

