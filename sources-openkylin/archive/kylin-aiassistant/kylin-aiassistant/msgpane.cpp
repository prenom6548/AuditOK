void CMsgPane::onSendDataCollectWithProps(const QString &eventCode, const QString &pageName, const QVariantMap &customProps)
{
    KTrackData *node = kdk_dia_data_init(KEVENTSOURCE_DESKTOP, KEVENT_CLICK);

    // 构建自定义属性数组
    int propCount = customProps.size();
    QList<QByteArray> keyBufs, valBufs;
    QVector<KCustomProperty> props(propCount);
    int i = 0;
    for (auto it = customProps.cbegin(); it != customProps.cend(); ++it, ++i) {
        keyBufs.append(it.key().toLocal8Bit());
        valBufs.append(it.value().toString().toLocal8Bit());
        props[i].key   = keyBufs.last().data();
        props[i].value = valBufs.last().data();
    }

    if (propCount > 0) {
        kdk_dia_append_custom_property(node, props.data(), propCount);
    }

    kdk_dia_upload_default(node, eventCode.toLocal8Bit().data(), pageName.toLocal8Bit().data());
    kdk_dia_data_free(node);
}

