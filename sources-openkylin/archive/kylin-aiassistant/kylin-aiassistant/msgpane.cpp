///

///
/// \brief CMsgPane::openSchedule
/// 通过日历D-Bus接口打开日历
/// \param todoListJson 待办列表JSON字符串，格式为 [{"currentYear":2025,"currentMonth":3,"currentDay":25,"content":"待办内容"},...]，从第一个待办项解析日期
///
void CMsgPane::openSchedule(QString todoListJson)
{
    KyInfo() << "openSchedule todoListJson: " << todoListJson;

    // 解析JSON字符串，从第一个待办项提取日期
    int year = 0, month = 0, day = 0;
    if (!todoListJson.isEmpty()) {
        QJsonParseError error;
        QJsonDocument doc = QJsonDocument::fromJson(todoListJson.toUtf8(), &error);
        if (error.error == QJsonParseError::NoError && doc.isArray()) {
            QJsonArray jsonArray = doc.array();
            // 只解析第一个待办项的日期
            if (!jsonArray.isEmpty()) {
                QJsonValue firstValue = jsonArray.at(0);
                if (firstValue.isObject()) {
                    QJsonObject obj = firstValue.toObject();
                    year = obj["currentYear"].toInt(0);
                    month = obj["currentMonth"].toInt(0);
                    day = obj["currentDay"].toInt(0);
                    KyInfo() << "Parsed date from first todo: " << year << "-" << month << "-" << day;
                }
            }
        } else {
            KyWarning() << "Failed to parse todoListJson:" << error.errorString();
        }
    }

    // 如果解析失败，使用当前日期
    if (year <= 0 || month <= 0 || day <= 0) {
        KyWarning() << "No valid date found in todoListJson, using current date";
        QDate currentDate = QDate::currentDate();
        year = currentDate.year();
        month = currentDate.month();
        day = currentDate.day();
    }

    // 创建D-Bus接口
    QDBusInterface *calendarInterface = new QDBusInterface(
        "org.ukui.calendar.Notifications",
        "/org/ukui/calendar/Notifications",
        "org.ukui.calendar.Notifications",
        QDBusConnection::sessionBus(),
        this
    );
    
    if (!calendarInterface->isValid()) {
        KyWarning() << "Failed to create D-Bus interface for calendar:" 
                    << QDBusConnection::sessionBus().lastError().message();
        delete calendarInterface;
        return;
    }
    
    // 调用OpenSchedule方法打开日历并跳转到指定日期
    QDBusReply<bool> reply = calendarInterface->call(
        "OpenSchedule",
        day, month, year
    );
    
    if (!reply.isValid()) {
        KyWarning() << "OpenSchedule call failed:" << reply.error().message();
    } else {
        QString schedule_date = QString("%1-%2-%3")
            .arg(year, 4, 10, QChar('0'))
            .arg(month, 2, 10, QChar('0'))
            .arg(day, 2, 10, QChar('0'));
        KyInfo() << "Successfully opened calendar for date: " << schedule_date;
    }
    
    delete calendarInterface;
}

///
/// \brief CMsgPane::addTodoToSchedule
/// 通过ScheduleNotification接口将待办添加到日程
/// \param todoListJson 待办事项JSON字符串，数组元素包含日期和内容字段等，格式为 [{"currentYear":2025,"currentMonth":3,"currentDay":25,"content":"待办内容"},...]
///
void CMsgPane::addTodoToSchedule(QString todoListJson)
{
    KyInfo() << "addTodoToSchedule " << todoListJson;

    // 创建D-Bus接口（复用，避免重复创建）
    QDBusInterface *notificationInterface = new QDBusInterface(
        "org.ukui.calendar.Notifications",
        "/org/ukui/calendar/Notifications",
        "org.ukui.calendar.Notifications",
        QDBusConnection::sessionBus(),
        this
    );
    
    if (!notificationInterface->isValid()) {
        KyWarning() << "Failed to create D-Bus interface for ScheduleNotification:" 
                    << QDBusConnection::sessionBus().lastError().message();
        delete notificationInterface;
        return;
    }
    
    QJsonParseError parseError;
    QJsonDocument inputDoc = QJsonDocument::fromJson(todoListJson.toUtf8(), &parseError);
    if (parseError.error != QJsonParseError::NoError || !inputDoc.isArray()) {
        KyWarning() << "Invalid todo list json:" << parseError.errorString();
        delete notificationInterface;
        return;
    }

    QJsonArray array = inputDoc.array();
    for (const QJsonValue &item : array) {
        if (!item.isObject()) {
            continue;
        }

        QJsonObject obj = item.toObject();
        int hour = obj.value("hour").toInt(0);
        int minute = obj.value("minute").toInt(0);
        int currentDay = obj.value("currentDay").toInt(0);
        int currentMonth = obj.value("currentMonth").toInt(0);
        int currentYear = obj.value("currentYear").toInt(0);
        int endMinute = obj.value("endMinute").toInt(0);
        int endHour = obj.value("endHour").toInt(0);
        QString todoItem = obj.value("content").toString();

        if (currentYear <= 0 || currentMonth <= 0 || currentDay <= 0 || todoItem.isEmpty()) {
            KyWarning() << "Skip invalid todo item, missing date or content";
            continue;
        }

        QDBusReply<bool> reply = notificationInterface->call(
            "ScheduleNotification",
            hour, minute, currentDay, currentMonth, currentYear,
            endMinute, endHour,
            todoItem
        );

        if (!reply.isValid()) {
            KyWarning() << "ScheduleNotification call failed for todo '" << todoItem 
                        << "':" << reply.error().message();
        } else {
            KyInfo() << "Successfully added schedule: " << todoItem << " on " 
                     << currentYear << "-" << currentMonth << "-" << currentDay;
        }
    }

    delete notificationInterface;
}

// 解析待办时间
static bool parseTodoTimeToken(const QString &timeText, int &hour, int &minute, QString *resolvedPeriod = nullptr, const QString &defaultPeriod = QString())
{
    QRegularExpression timeRegex(
        R"(^(上午|下午|中午|晚上|凌晨)?\s*(\d{1,2})(?:(?:\s*[:：]\s*(\d{1,2}))|(?:\s*(?:点|时)\s*(\d{1,2})?\s*分?))?\s*$)"
    );
    QRegularExpressionMatch match = timeRegex.match(timeText.trimmed());
    if (!match.hasMatch()) {
        return false;
    }

    QString period = match.captured(1).trimmed();
    if (period.isEmpty()) {
        period = defaultPeriod;
    }

    hour = match.captured(2).toInt();
    minute = 0;
    if (!match.captured(3).isEmpty()) {
        minute = match.captured(3).toInt();
    } else if (!match.captured(4).isEmpty()) {
        minute = match.captured(4).toInt();
    }

    if (minute < 0 || minute > 59 || hour < 0 || hour > 23) {
        return false;
    }

    if (period == "下午" || period == "晚上") {
        if (hour < 12) {
            hour += 12;
        }
    } else if (period == "中午") {
        if (hour >= 1 && hour <= 10) {
            hour += 12;
        }
    } else if (period == "凌晨") {
        if (hour == 12) {
            hour = 0;
        }
    }

    if (hour < 0 || hour > 23) {
        return false;
    }

    if (resolvedPeriod != nullptr) {
        *resolvedPeriod = period;
    }

    return true;
}

// 提取代办时间范围
static bool extractTodoTimeRange(QString &todoItem, int &hour, int &minute, int &endHour, int &endMinute)
{
    QString originalTodoItem = todoItem;

    QRegularExpression timeRangeRegex(
        R"(((?:上午|下午|中午|晚上|凌晨)?\s*\d{1,2}(?:(?:\s*[:：]\s*\d{1,2})|(?:\s*(?:点|时)\s*\d{0,2}\s*分?))?)\s*(?:到|至|-|~|～|—|－)\s*((?:上午|下午|中午|晚上|凌晨)?\s*\d{1,2}(?:(?:\s*[:：]\s*\d{1,2})|(?:\s*(?:点|时)\s*\d{0,2}\s*分?))?))"
    );
    QRegularExpressionMatch match = timeRangeRegex.match(todoItem);

    if (match.hasMatch()) {
        QString startToken = match.captured(1).trimmed();
        QString endToken = match.captured(2).trimmed();
        QString startPeriod;
        int parsedHour = 0;
        int parsedMinute = 0;
        int parsedEndHour = 0;
        int parsedEndMinute = 0;

        if (!parseTodoTimeToken(startToken, parsedHour, parsedMinute, &startPeriod)) {
            return false;
        }

        if (!parseTodoTimeToken(endToken, parsedEndHour, parsedEndMinute, nullptr, startPeriod)) {
            return false;
        }

        todoItem.remove(match.capturedStart(0), match.capturedLength(0));
        todoItem = todoItem.trimmed();
        todoItem.remove(QRegularExpression(R"(^[：:，,、\-\s]+)"));
        todoItem = todoItem.trimmed();

        if (todoItem.isEmpty()) {
            todoItem = originalTodoItem;
            return false;
        }

        hour = parsedHour;
        minute = parsedMinute;
        endHour = parsedEndHour;
        endMinute = parsedEndMinute;
        return true;
    }

    // 如果没有时间范围，则尝试匹配单个时间点
    QRegularExpression singleTimeRegex(
        R"((上午|下午|中午|晚上|凌晨)?\s*(\d{1,2})(?:(?:\s*[:：]\s*(\d{1,2}))|(?:\s*(?:点|时)\s*(\d{0,2})\s*分?))?)",
        QRegularExpression::MultilineOption
    );

    match = singleTimeRegex.match(todoItem);
    if (match.hasMatch()) {
        QString period = match.captured(1).trimmed();
        int parsedHour = match.captured(2).toInt();
        int parsedMinute = 0;

        if (!match.captured(3).isEmpty()) {
            parsedMinute = match.captured(3).toInt();
        } else if (!match.captured(4).isEmpty()) {
            parsedMinute = match.captured(4).toInt();
        }

        // 处理上午/下午
        if (period == "下午" || period == "晚上") {
            if (parsedHour < 12) {
                parsedHour += 12;
            }
        } else if (period == "中午") {
            if (parsedHour >= 1 && parsedHour <= 10) {
                parsedHour += 12;
            }
        }

        // 清理时间文本
        todoItem.remove(match.capturedStart(0), match.capturedLength(0));
        todoItem = todoItem.trimmed();
        todoItem.remove(QRegularExpression(R"(^[：:，,、\-\s]+)"));
        todoItem = todoItem.trimmed();

        if (todoItem.isEmpty()) {
            todoItem = originalTodoItem;
            return false;
        }

        // 设置时间：开始时间为解析的时间，结束时间默认加1小时
        hour = parsedHour;
        minute = parsedMinute;
        endHour = (parsedHour + 1) % 24;
        endMinute = parsedMinute;

        return true;
    }

    return false;
}

// 解析待办日期文本
static bool parseTodoDatePart(const QString &datePart, int &year, int &month, int &day)
{
    const QString normalizedDatePart = datePart.trimmed();
    if (normalizedDatePart.isEmpty()) {
        return false;
    }

    QRegularExpression chineseDateRegex(R"((\d{4})年(\d{1,2})月(\d{1,2})日)");
    QRegularExpressionMatch chineseMatch = chineseDateRegex.match(normalizedDatePart);
    if (chineseMatch.hasMatch()) {
        year = chineseMatch.captured(1).toInt();
        month = chineseMatch.captured(2).toInt();
        day = chineseMatch.captured(3).toInt();
        return year > 0 && month > 0 && day > 0;
    }

    QRegularExpression dottedDateRegex(R"((\d{4})[.\-/](\d{1,2})[.\-/](\d{1,2}))");
    QRegularExpressionMatch dottedMatch = dottedDateRegex.match(normalizedDatePart);
    if (dottedMatch.hasMatch()) {
        year = dottedMatch.captured(1).toInt();
        month = dottedMatch.captured(2).toInt();
        day = dottedMatch.captured(3).toInt();
        return year > 0 && month > 0 && day > 0;
    }

    const QStringList isoParts = normalizedDatePart.split("-");
    if (isoParts.size() >= 3) {
        year = isoParts[0].toInt();
        month = isoParts[1].toInt();
        day = isoParts[2].toInt();
        return year > 0 && month > 0 && day > 0;
    }

    return false;
}

QString CMsgPane::getTodoList(QString todoMessage)
{
    KyInfo() << "todoMessage " << todoMessage;
    QVariantList todoList;  // 用于返回的待办列表

    QString plainMessage = todoMessage;
    plainMessage.remove(QRegularExpression("<[^>]+>"));

    // 判断输入是日期格式（"2025-03-25"）还是待办事项消息
    // 如果包含 "# " 开头，说明是待办事项格式，需要解析
    if ((plainMessage.contains("## ") || plainMessage.contains("# ")) && plainMessage.contains("- ")) {
        // 解析待办事项格式: "## 日期 星期\n- 待办事项1\n- 待办事项2\n"
        QStringList lines = plainMessage.split("\n", QString::SkipEmptyParts);
        int currentYear = 0;
        int currentMonth = 0;
        int currentDay = 0;

        for (const QString &line : lines) {
            QString trimmedLine = line.trimmed();

            // 检查是否是日期行（格式: "## 日期 星期" 或 "# YYYY年MM月DD日 星期"）
            if (trimmedLine.startsWith("## ") || trimmedLine.startsWith("# ")) {
                // 提取日期部分（去掉 "#"/"##" 前缀和星期部分）
                QString datePart = trimmedLine.startsWith("## ")
                        ? trimmedLine.mid(3).trimmed()
                        : trimmedLine.mid(2).trimmed();
                // 移除星期部分（星期可能在日期后面，用空格分隔）
                int spaceIndex = datePart.indexOf(" ");
                if (spaceIndex > 0) {
                    datePart = datePart.left(spaceIndex);
                }

                if (parseTodoDatePart(datePart, currentYear, currentMonth, currentDay)) {
                    KyInfo() << "Parsed date: " << currentYear << "-" << currentMonth << "-" << currentDay;
                } else {
                    currentYear = 0;
                    currentMonth = 0;
                    currentDay = 0;
                }
            }
            // 检查是否是待办事项行（格式: "- 待办事项"）
            else if (trimmedLine.startsWith("- ") && currentYear > 0) {
                QString todoItem = trimmedLine.mid(2).trimmed();
                if (!todoItem.isEmpty()) {
                    int todoHour = 0;
                    int todoMinute = 0;
                    int todoEndHour = 0;
                    int todoEndMinute = 0;
                    extractTodoTimeRange(todoItem, todoHour, todoMinute, todoEndHour, todoEndMinute);

                    // 添加到返回列表
                    QVariantMap todoMap;
                    todoMap["hour"] = todoHour;
                    todoMap["minute"] = todoMinute;
                    todoMap["currentDay"] = currentDay;
                    todoMap["currentMonth"] = currentMonth;
                    todoMap["currentYear"] = currentYear;
                    todoMap["endMinute"] = todoEndMinute;
                    todoMap["endHour"] = todoEndHour;
                    todoMap["content"] = todoItem;
                    todoList.append(todoMap);
                }
            }
        }
    }

    // 将QVariantList转换为JSON字符串
    QJsonArray jsonArray;
    for (const QVariant &item : todoList) {
        QVariantMap map = item.toMap();
        QJsonObject jsonObj;
        jsonObj["hour"] = map["hour"].toInt();
        jsonObj["minute"] = map["minute"].toInt();
        jsonObj["currentDay"] = map["currentDay"].toInt();
        jsonObj["currentMonth"] = map["currentMonth"].toInt();
        jsonObj["currentYear"] = map["currentYear"].toInt();
        jsonObj["endMinute"] = map["endMinute"].toInt();
        jsonObj["endHour"] = map["endHour"].toInt();
        jsonObj["content"] = map["content"].toString();

        jsonArray.append(jsonObj);
    }

    QJsonDocument doc(jsonArray);
    QString jsonString = doc.toJson(QJsonDocument::Compact);
    KyInfo() << "getTodoList return JSON: " << jsonString;

    return jsonString;
}

