int CMsgPane::xdgOpen(QString path)
{
    // 1. 检查路径是否存在
    if (!QFileInfo::exists(path)) {
        KyInfo() << "xdgOpen failed: path does not exist:" << path;
        return 1;
    }

    // 2. 创建QProcess对象（栈上创建，自动释放）
    QProcess process;
    // 设置要执行的命令和参数
    process.start("xdg-open", QStringList() << path);

    // 3. 等待进程退出并获取退出码（设置超时时间，根据需求调整）
    // waitForFinished：等待进程执行完成（返回是否正常退出）
    if (!process.waitForFinished(10000)) { // 10秒超时（xdg-open通常很快退出）
        KyInfo() << "xdgOpen failed: process timeout or crashed";
        KyInfo() << "Error reason:" << process.errorString();
        process.kill(); // 超时后杀死进程，避免僵尸进程
        return -1;
    }

    // 4. 获取xdg-open的实际返回值（退出码）
    int exitCode = process.exitCode();
    if (exitCode == 0) {
        KyInfo() << "xdgOpen successfully executed! exit code:" << exitCode;
        return 0;
    } else {
        KyInfo() << "xdgOpen failed: exit code =" << exitCode;
        QByteArray stderrData = process.readAllStandardError();
        if (!stderrData.isEmpty()) {
            KyInfo() << "xdg-open error output:" << stderrData;
        }
        return exitCode;
    }

    return 0;
}

