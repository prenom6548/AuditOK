void CMsgPane::syncGatewayPairing()
{
    QString token = ConfigManager::getInstance()->getConfigValue("gateway-token").toString().trimmed();
    if (!token.isEmpty()) {
        return;
    }

    UnixHttpResponse r1 = requestGatewaySocketFirst(
        QStringLiteral("POST"), QStringLiteral("/admin/paircode/new"));
    if (r1.statusCode == 0) {
        KyInfo() << "syncGatewayPairing: pair code request failed:" << r1.errorString;
        return;
    }

    if (r1.statusCode != 200 && r1.statusCode != 400) {
        KyInfo() << "syncGatewayPairing: pair code unexpected status" << r1.statusCode
                 << "body:" << QString::fromUtf8(r1.body).left(500);
        return;
    }

    QJsonDocument doc1 = QJsonDocument::fromJson(r1.body);
    if (!doc1.isObject()) {
        KyInfo() << "syncGatewayPairing: invalid paircode response, body:"
                 << QString::fromUtf8(r1.body).left(200);
        return;
    }

    QJsonObject obj1 = doc1.object();
    const QJsonValue pairingRequiredValue = obj1.value(QStringLiteral("pairing_required"));
    if (pairingRequiredValue.isBool() && !pairingRequiredValue.toBool()) {
        KyInfo() << "syncGatewayPairing: pairing not required";
        return;
    }

    QString code = obj1.value("pairing_code").toString();
    if (code.isEmpty()) {
        KyInfo() << "syncGatewayPairing: no pairing code available";
        return;
    }

    KyInfo() << "syncGatewayPairing: pairing code obtained:" << code;

    QMap<QString, QString> headers;
    headers[QStringLiteral("X-Pairing-Code")] = code;
    UnixHttpResponse r2 = requestGatewaySocketFirst(
        QStringLiteral("POST"), QStringLiteral("/pair"), headers);
    if (r2.statusCode == 0) {
        KyInfo() << "syncGatewayPairing: pairing failed:" << r2.errorString;
        return;
    }

    if (r2.statusCode != 200) {
        KyInfo() << "syncGatewayPairing: pairing unexpected status" << r2.statusCode
                 << "body:" << QString::fromUtf8(r2.body).left(500);
        return;
    }

    QJsonDocument doc2 = QJsonDocument::fromJson(r2.body);
    if (!doc2.isObject()) {
        KyInfo() << "syncGatewayPairing: invalid pairing response, body:"
                 << QString::fromUtf8(r2.body).left(200);
        return;
    }

    QJsonObject obj2 = doc2.object();
    if (obj2.contains("token")) {
        QString newToken = obj2["token"].toString();
        ConfigManager::getInstance()->updateConfig("gateway-token", newToken);
        KyInfo() << "syncGatewayPairing: succeeded, token saved";
        return;
    }

    KyInfo() << "syncGatewayPairing: pairing response missing token";
}

bool CMsgPane::validateAndRefreshGatewayToken()
{
    QString token = ConfigManager::getInstance()->getConfigValue("gateway-token").toString().trimmed();
    if (token.isEmpty()) {
        syncGatewayPairing();
        return true;
    }

    QMap<QString, QString> headers;
    headers[QStringLiteral("Authorization")] = QStringLiteral("Bearer ") + token;
    UnixHttpResponse resp = requestGatewaySocketFirst(
        QStringLiteral("GET"), QStringLiteral("/api/health"), headers);

    if (resp.statusCode == 200) {
        KyInfo() << "validateAndRefreshGatewayToken: token is valid";
        return true;
    }

    if (resp.statusCode == 401) {
        KyInfo() << "validateAndRefreshGatewayToken: token invalidated (401), re-pairing";
        ConfigManager::getInstance()->updateConfig("gateway-token", "");
        syncGatewayPairing();
        return true;
    }

    if (resp.statusCode == 0) {
        KyInfo() << "validateAndRefreshGatewayToken: gateway unreachable, assuming token still valid:"
                 << resp.errorString;
        return true;
    }

    KyInfo() << "validateAndRefreshGatewayToken: unexpected status" << resp.statusCode
             << "body:" << QString::fromUtf8(resp.body).left(200)
             << "- assuming token still valid";
    return true;
}





