void CMsgPane::saveToDatabase(int msgInex, QString message)
{
    QString addressAsString;
    if (m_chatType == TASK_MODE) {
        TaskSession* activeSession = m_taskSessionManager->getSession(m_taskSessionManager->getActiveSessionUuid());
        int historyId = activeSession ? activeSession->historyId : 0;
        QString activeUuid = m_taskSessionManager->getActiveSessionUuid();
        if (!activeUuid.isEmpty()) {
            addressAsString = QString::number(historyId);
            m_database->insertOneWithModeTypeAndUuid(addressAsString, msgInex, message, 0, 1, activeUuid);
            m_database->updateOperateTime(addressAsString, msgInex);
            int maxHistoryId = getCurrentMaxHistoryId();
            if(historyId == maxHistoryId)
            {
                m_database->updateMaxHistoryId(maxHistoryId + 1);
            }
        }
    } else {
        int curID = m_chat->getSession();
        addressAsString = QString::number(curID);
        m_database->insertOne(addressAsString, msgInex, message, 0);
        m_database->updateOperateTime(addressAsString, msgInex);

        int maxHistoryId = getCurrentMaxHistoryId();
        if(curID == maxHistoryId)
        {
            m_database->updateMaxHistoryId(maxHistoryId + 1);
        }
    }

    // 从消息 JSON 中提取文件信息并保存到文件引用表
    QJsonDocument jsonDoc = QJsonDocument::fromJson(message.toUtf8());
    if (jsonDoc.isObject()) {
        QJsonObject jsonObj = jsonDoc.object();
        QString author = jsonObj.value("author").toString();

        // 只处理用户消息
        if (author == "User") {
            // 检查是否是生成待办消息，如果是则不保存文件到文件引用数据库
            bool isGenerateToDo = jsonObj.value("isGenerateToDo").toBool(false);
            if (!isGenerateToDo) {
                QString fileType = jsonObj.value("fileType").toString();
                QString documents = jsonObj.value("documents").toString();

                // 如果有文件信息，保存到文件引用表
                if (!fileType.isEmpty() && !documents.isEmpty()) {
                    DocumentReferenceDatabase::getInstance()->insertDocumentReference(addressAsString, fileType, documents);
                }
            }
        }
    }

    int curWinMode = getCurWinMode();
    //窗口模式
    if(curWinMode == 3){
         getDialogueList();
    }

}

