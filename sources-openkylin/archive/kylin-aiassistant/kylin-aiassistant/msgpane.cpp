static ParsedKybotCronRunOutput parseKybotCronRunOutput(const QString& rawOutput)
{
    ParsedKybotCronRunOutput parsed;
    parsed.message = rawOutput;
    const int wrapperPos = rawOutput.indexOf(QStringLiteral("\"kylin_cron_v1\""));

    QJsonParseError jsonErr;
    const QJsonDocument doc = QJsonDocument::fromJson(rawOutput.toUtf8(), &jsonErr);
    if (jsonErr.error != QJsonParseError::NoError || !doc.isObject()) {
        if (wrapperPos >= 0) {
            const QString looseMessage =
                extractLooseJsonStringField(rawOutput, QStringLiteral("message"), wrapperPos);
            if (!looseMessage.isEmpty()) {
                parsed.message = looseMessage;
            }

            parsed.thinking =
                extractLooseJsonStringField(rawOutput, QStringLiteral("thinking"), wrapperPos);
            parsed.thinking.replace(QStringLiteral("<"), QStringLiteral("&lt;"));
            parsed.thinking.replace(QStringLiteral(">"), QStringLiteral("&gt;"));
        }
        return parsed;
    }

    const QJsonObject root = doc.object();
    const QJsonObject payload = root.value(QStringLiteral("kylin_cron_v1")).toObject();
    if (payload.isEmpty()) {
        if (wrapperPos < 0) {
            return parsed;
        }

        const QString looseMessage =
            extractLooseJsonStringField(rawOutput, QStringLiteral("message"), wrapperPos);
        if (!looseMessage.isEmpty()) {
            parsed.message = looseMessage;
        }

        parsed.thinking =
            extractLooseJsonStringField(rawOutput, QStringLiteral("thinking"), wrapperPos);
        parsed.thinking.replace(QStringLiteral("<"), QStringLiteral("&lt;"));
        parsed.thinking.replace(QStringLiteral(">"), QStringLiteral("&gt;"));
        return parsed;
    }

    parsed.message = payload.value(QStringLiteral("message")).toString(rawOutput);
    parsed.thinking = payload.value(QStringLiteral("thinking")).toString();
    parsed.toolCalls = payload.value(QStringLiteral("tool_calls")).toArray();
    parsed.thinking.replace(QStringLiteral("<"), QStringLiteral("&lt;"));
    parsed.thinking.replace(QStringLiteral(">"), QStringLiteral("&gt;"));
    return parsed;
}

