static std::vector<Message> buildChatHistoryFromConversationList(const QStringList &list)
{
    std::vector<Message> history;
    bool isSkip = false;  //用于标识文档问答和携带指令的提问，如果遇到此类提问，不拼接下一条回答

    for (const QString &jsonStr : list) {
        if (isSkip) {
            isSkip = false;
            continue;
        }

        QJsonDocument jsonDoc = QJsonDocument::fromJson(jsonStr.toUtf8());
        if (!jsonDoc.isObject()) {
            qWarning() << "Invalid JSON:" << jsonStr;
            continue;
        }

        QJsonObject jsonObj = jsonDoc.object();
        QString author = jsonObj.value("author").toString();
        if (author.isEmpty()) {
            author = jsonObj.value("sentByUser").toBool(false)
                    ? QStringLiteral("User") : QStringLiteral("Bot");
        }
        std::string msg = removeHtmlTags(jsonObj.value("message").toString()).toStdString();
        QString command = jsonObj.value("msgHead").toString();
        QString filePath = jsonObj.value("documentPath").toString();
        if (command != "" || filePath != "") {
            history.clear();
            isSkip = true;
            continue;
        }

        Message m;
        if (author == "User") {
            m.user = msg;
        } else {
            m.assistant = msg;
        }
        history.push_back(m);
    }

    return history;
}

void CMsgPane::loadHistoryBySessionId(QString sessionId)
{
    m_database->setUnreadFlag(sessionId, 0);
    int modeType = m_database->getSessionModeType(sessionId);
    const bool isVoiceAssistantHistory = sessionId.startsWith(QStringLiteral("v_")) && modeType == 1;
    if (modeType == 1 && !isVoiceAssistantHistory) {
        loadTaskSessionHistory(sessionId);
        return;
    }
    if (isVoiceAssistantHistory) {
        // Legacy v_* 旧语音会话：无 Gateway 任务会话，仅展示历史。
        m_chatType = NORMAL;
        QStringList voiceHistory = m_database->selectBySessionID(sessionId);
        voiceHistory = dedupeConsecutiveVoiceErrorMessages(voiceHistory);
        Q_EMIT loadConversation(normalizeVoiceAssistantHistoryMessages(voiceHistory));
        Q_EMIT sessionReplyStatusChanged(sessionId, false, false);
        Q_EMIT modifyDialogueListFlag("");
        return;
    }

    //KyInfo() << "Q_EMIT loadHistoryBySessionId sessionId=" << sessionId;
    QStringList list = filterVoiceMessagesFromTextHistory(m_database->selectBySessionID(sessionId));
    if(m_chat->getSession() != sessionId.toInt()){
        //onPauseRead();//切换对话时，若对话不是当前对话停止朗读//TODO：需要基于readercontrol实现对应逻辑

    }
    m_chat->setSession(sessionId.toInt());
    Q_EMIT changeSessionId(m_chat->getSession());
    Q_EMIT loadConversation(list);
    Q_EMIT sessionReplyStatusChanged(sessionId, false, false);
    Q_EMIT modifyDialogueListFlag("");//恢复删除后列表的删除选中状态

    // 从数据库读取文件引用信息
    QString documentJson = DocumentReferenceDatabase::getInstance()->selectDocumentReferenceBySessionID(sessionId);

    // 如果找到文件引用信息，发送信号到前端
    if (!documentJson.isEmpty()) {
        Q_EMIT restoreDocumentReference(documentJson);
    }

    qDebug() << "loadHistoryBySessionId   initWithHistory ";
    m_chat->initWithHistory(buildChatHistoryFromConversationList(list));

    //切换上下文时，重新设置模型
    m_chat->setNLPModel(ConfigManager::getInstance()->getConfigValue("cur-nlp-model").toString());

}

void CMsgPane::loadTaskSessionHistory(const QString& sessionId)
{
    const QString sessionUuidInDb = m_database->selectSessionUuidBySessionID(sessionId);
    bool isVoiceHistory = isVoiceAssistantSessionUuid(sessionUuidInDb);
    
    // 如果 sessionUuidInDb 不是 "voice-assistant"，检查数据中是否包含 speechFlag 字段
    // 以判断是否是使用 kylin-bot session uuid 存储的语音历史
    if (!isVoiceHistory && !sessionUuidInDb.isEmpty()) {
        QStringList checkList = m_database->selectBySessionID(sessionId);
        for (const QString &item : checkList) {
            QJsonParseError jsonErr;
            const QJsonDocument jsonDoc = QJsonDocument::fromJson(item.toUtf8(), &jsonErr);
            if (jsonErr.error == QJsonParseError::NoError && jsonDoc.isObject()
                    && isVoiceAssistantStoredMessage(jsonDoc.object())) {
                isVoiceHistory = true;
                break;
            }
        }
    }

    QStringList list;
    if (isVoiceHistory) {
        list = dedupeConsecutiveVoiceErrorMessages(m_database->selectBySessionID(sessionId));
        list = normalizeVoiceAssistantHistoryMessages(list);
    } else {
        list = filterVoiceMessagesFromTextHistory(m_database->selectBySessionID(sessionId));
    }

    const QString uuid = taskSessionUuidForLoadedHistory(sessionId, sessionUuidInDb);

    int historyId = sessionId.toInt();

    if (m_taskSessionManager) {
        QString activeUuid = m_taskSessionManager->getActiveSessionUuid();
        if (!activeUuid.isEmpty() && activeUuid != uuid) {
            TaskSession* activeSession = m_taskSessionManager->getSession(activeUuid);
            if (activeSession && activeSession->isReplying) {
                m_taskSessionManager->deactivateSession();
            } else {
                m_backendRecvMessage.remove(activeUuid);
                m_taskSessionManager->closeSession(activeUuid);
            }
        }
    }

    TaskSession* session = m_taskSessionManager->getSession(uuid);

    if (!session) {
        m_taskSessionManager->createSession(uuid, historyId);
        session = m_taskSessionManager->getSession(uuid);
    } else {
        m_taskSessionManager->activateSession(uuid);
    }

    const bool isReplying = session && session->isReplying;
    Q_EMIT updateTaskSessionIsReplying(isReplying);

    new_reply = true;
    recv_reasoning_message = "";
    m_chatType = TASK_MODE;

    m_chat->setSession(historyId);
    Q_EMIT changeSessionId(historyId);
    Q_EMIT changeTaskSessionId(m_taskSessionManager->getActiveSessionUuid());

    Q_EMIT loadConversation(normalizeTaskSessionHistoryMessages(list));
    Q_EMIT sessionReplyStatusChanged(sessionId, isReplying, false);

    if (m_backendRecvMessage.contains(uuid) && !m_backendRecvMessage[uuid].isEmpty()) {
        QString header = m_backendRecvMessageHeader.value(uuid, "");
        pushMsg("addRecvMsg", header, m_backendRecvMessage[uuid]);
        if (m_backendTaskToolCalls.contains(uuid)) {
            for (const QJsonValue &toolFrame : m_backendTaskToolCalls[uuid]) {
                if (toolFrame.isObject()) {
                    Q_EMIT updateTaskToolCalls(QString::fromUtf8(QJsonDocument(toolFrame.toObject()).toJson(QJsonDocument::Compact)));
                }
            }
        }
        recv_reasoning_message = m_backendRecvReasoningMsg.value(uuid, "");
        if (!recv_reasoning_message.isEmpty()) {
            pushMsg("updateReasoningMsg", "", recv_reasoning_message);
        }
        new_reply = false;
    } else if (session && session->isReplying) {
        // Session is still replying but only tool calls cached (no text yet).
        // Create an empty Bot placeholder so the first real-time updateMsg
        // does not overwrite the User message (loaded from DB with isFirst=true).
        QJsonObject header;
        header["modelMsg"] = tr("Content generated by AI");
        pushMsg("addRecvMsg", QJsonDocument(header).toJson(QJsonDocument::Compact), tr("Answering"));
        if (m_backendTaskToolCalls.contains(uuid)) {
            for (const QJsonValue &toolFrame : m_backendTaskToolCalls[uuid]) {
                if (toolFrame.isObject()) {
                    Q_EMIT updateTaskToolCalls(QString::fromUtf8(QJsonDocument(toolFrame.toObject()).toJson(QJsonDocument::Compact)));
                }
            }
        }
        recv_reasoning_message = m_backendRecvReasoningMsg.value(uuid, "");
        if (!recv_reasoning_message.isEmpty()) {
            pushMsg("updateReasoningMsg", "", recv_reasoning_message);
        }
        new_reply = false;
    }

    // 加载对话历史上下文（语音通话历史恢复时，通过 history 注入模型上下文）
    m_chat->initWithHistory(buildChatHistoryFromConversationList(list));
}

