// ---------------------------------------------------------------------------
// Current locale state
// ---------------------------------------------------------------------------

function detectBrowserLocale(): Locale {
  if (typeof navigator === 'undefined') return 'en';
  const lang = (navigator.language || navigator.languages?.[0] || 'en').toLowerCase();
  if (lang.startsWith('zh')) return 'zh';
  if (lang.startsWith('tr')) return 'tr';
  return 'en';
}

export function parseLocale(value: string | null | undefined): Locale {
  const localeStr = (value ?? '').toLowerCase();
  if (localeStr.startsWith('zh')) return 'zh';
  if (localeStr.startsWith('tr')) return 'tr';
  if (!localeStr) return detectBrowserLocale();
  return 'en';
}

/** Prefer QML/host `locale` query, then the browser/system language. */
export function detectHostLocale(): Locale {
  if (typeof window !== 'undefined') {
    try {
      const fromQuery = new URLSearchParams(window.location.search).get('locale');
      if (fromQuery) return parseLocale(fromQuery);
    } catch {
      // ignore invalid location
    }
  }
  return detectBrowserLocale();
}

let currentLocale: Locale = detectHostLocale();

export function getLocale(): Locale {
  return currentLocale;
}

export function setLocale(locale: Locale): void {
  currentLocale = locale;
}

// ---------------------------------------------------------------------------
// Translation function
// ---------------------------------------------------------------------------

/**
 * Translate a key using the current locale. Returns the key itself if no
 * translation is found.
 */
export function t(key: string): string {
  return translations[currentLocale]?.[key] ?? translations.en[key] ?? key;
}

/**
 * Get the translation for a specific locale. Falls back to English, then to the
 * raw key.
 */
export function tLocale(key: string, locale: Locale): string {
  return translations[locale]?.[key] ?? translations.en[key] ?? key;
}

/** Translate and replace `{name}`-style placeholders. */
export function tf(key: string, vars: Record<string, string | number> = {}): string {
  let out = t(key);
  for (const [k, v] of Object.entries(vars)) {
    out = out.split(`{${k}}`).join(String(v));
  }
  return out;
}

export function formatCompactCount(n: number): string {
  if (currentLocale === 'zh') {
    if (n >= 10_000) return `${(n / 10_000).toFixed(1)}万`;
    if (n >= 1_000) return `${(n / 1_000).toFixed(1)}千`;
    return String(n);
  }
  if (n >= 1_000_000) return `${(n / 1_000_000).toFixed(1)}M`;
  if (n >= 1_000) return `${(n / 1_000).toFixed(1)}K`;
  return String(n);
}

// ---------------------------------------------------------------------------
// React hook
// ---------------------------------------------------------------------------

/**
 * React hook that fetches the locale from /api/status on mount and keeps the
 * i18n module in sync. Returns the current locale and a `t` helper bound to it.
 */
export function useLocale(): { locale: Locale; t: (key: string) => string } {
  const [locale, setLocaleState] = useState<Locale>(currentLocale);

  useEffect(() => {
    setLocaleState(currentLocale);
  }, []);

  return {
    locale,
    t: (key: string) => tLocale(key, locale),
  };
}
