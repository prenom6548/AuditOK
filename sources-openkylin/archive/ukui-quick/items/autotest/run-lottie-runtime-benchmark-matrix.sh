#!/usr/bin/env bash
set -euo pipefail

if [[ $# -lt 1 || $# -gt 3 ]]; then
    printf 'usage: %s BENCHMARK_BINARY [ASSET_DIR] [REPORT_PATH]\n' "$0" >&2
    exit 2
fi

benchmark_binary=$1
asset_dir=${2:-${UKUI_LOTTIE_BENCHMARK_DIR:-}}
report_path=${3:-/tmp/ukui-quick-ticket11-lottie-runtime-matrix.md}
duration_ms=${UKUI_LOTTIE_BENCHMARK_DURATION_MS:-1000}

if [[ -z "$asset_dir" ]]; then
    printf 'asset directory is required: pass ASSET_DIR or UKUI_LOTTIE_BENCHMARK_DIR\n' >&2
    exit 2
fi
if [[ ! -x "$benchmark_binary" ]]; then
    printf 'benchmark binary is not executable: %s\n' "$benchmark_binary" >&2
    exit 2
fi
if [[ ! -d "$asset_dir" ]]; then
    printf 'asset directory does not exist: %s\n' "$asset_dir" >&2
    exit 2
fi
resource_count=$(find "$asset_dir" -maxdepth 1 -type f -name '*.lottie' | wc -l)
if [[ "$resource_count" -ne 14 ]]; then
    printf 'expected exactly 14 .lottie resources, found %s: %s\n' \
        "$resource_count" "$asset_dir" >&2
    exit 2
fi

work_dir=$(mktemp -d /tmp/ukui-quick-ticket11-benchmark.XXXXXX)
trap 'rm -rf "$work_dir"' EXIT
runtime_dir="$work_dir/runtime"
warm_home="$work_dir/warm-home"
mkdir -p "$runtime_dir" "$warm_home"
chmod 700 "$runtime_dir"
mkdir -p "$(dirname "$report_path")"

run_profile() {
    local cache_mode=$1
    local key_count=$2
    local physical_size=$3
    local cadence_fps=$4
    local profile=$5
    local output_file=$6
    local stdout_file="$work_dir/${cache_mode}-${key_count}-${physical_size}-${cadence_fps}-${profile}.stdout"
    local stderr_file="$work_dir/${cache_mode}-${key_count}-${physical_size}-${cadence_fps}-${profile}.stderr"
    local -a cache_args=()
    local home_value=
    if [[ "$cache_mode" == warm ]]; then
        cache_args+=(--warm-cache)
        home_value=$warm_home
    else
        home_value="$work_dir/cold-home-${key_count}-${physical_size}-${cadence_fps}-${profile}"
        mkdir -p "$home_value"
    fi

    if ! env HOME="$home_value" \
        QT_QPA_PLATFORM=offscreen \
        QT_QUICK_BACKEND=software \
        QT_QPA_PLATFORMTHEME=generic \
        GSETTINGS_BACKEND=memory \
        XDG_RUNTIME_DIR="$runtime_dir" \
        "$benchmark_binary" \
        --asset-dir "$asset_dir" \
        --hosts 64 \
        --keys "$key_count" \
        --size "$physical_size" \
        --cadence-fps "$cadence_fps" \
        --profile "$profile" \
        --playback-ms "$duration_ms" \
        "${cache_args[@]}" \
        --output "$output_file" >"$stdout_file" 2>"$stderr_file"; then
        cat "$stdout_file" >&2 || true
        cat "$stderr_file" >&2 || true
        printf 'benchmark profile failed: %s %s %s %s %s\n' \
            "$cache_mode" "$key_count" "$physical_size" "$cadence_fps" "$profile" >&2
        exit 1
    fi
}

# Prime the shared warm HOME in a separate production process before any row
# is labelled warm. The measured warm processes still create their own
# RuntimeService/scheduler/Hosts and exercise the production frame-cache
# prefill performed during Host setup.
warmup_report="$work_dir/warmup.md"
run_profile warm 16 24 30 steady "$warmup_report"

first_report=
{
    printf '# Ticket 11 production Lottie runtime benchmark matrix\n\n'
    printf 'This report is generated by the production RuntimeService benchmark harness. '
    printf 'Absolute timings are machine evidence, not CI hard thresholds.\n\n'
    printf -- '- Asset directory: `%s`\n' "$asset_dir"
    printf -- '- Benchmark binary: `%s`\n' "$benchmark_binary"
    printf -- '- Matrix runner: `%s`\n' "$0"
    printf -- '- Resource count: 14 external .lottie files (not copied by this runner)\n'
    printf -- '- Hosts per row: 64\n'
    printf -- '- Distinct-key rows: 16, 32, 56\n'
    printf -- '- Physical-size rows: 24, 32, 48\n'
    printf -- '- Cadence rows: 30, 60 FPS (submitted tick count is recorded per row)\n'
    printf -- '- Cold and warm/coalescing rows are separate process profiles.\n'
    printf -- '- Resize/theme churn is reported separately from the steady-size matrix.\n\n'

    printf '## Environment and resource evidence\n\n'
    printf 'The first completed profile contains the full machine/toolchain and SHA-256 evidence.\n\n'

    printf '## Steady-size matrix\n\n'
    printf '| Row | Cache | Profile | Keys target | Configured exact | Tick key range | Cumulative observed | Hosts | Physical px | Cadence target | Ticks submitted | Actual FPS | Source executor p95 ms | Queue p95 ms | Raster exec p95 ms | Raster completion p95 ms | GUI batch p95 ms | Host commit p95 ms | Raster jobs | Cache hits | Coalesced | Superseded | Dropped/stale | GUI batches | Budget |\n'
    printf '| --- | --- | --- | ---: | ---: | --- | ---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: | --- |\n'

    for cache_mode in cold warm; do
        for key_count in 16 32 56; do
            for physical_size in 24 32 48; do
                for cadence_fps in 30 60; do
                    profile_report="$work_dir/${cache_mode}-${key_count}-${physical_size}-${cadence_fps}-steady.md"
                    run_profile "$cache_mode" "$key_count" "$physical_size" "$cadence_fps" steady "$profile_report"
                    if [[ -z "$first_report" ]]; then
                        first_report=$profile_report
                        if ! grep -q '^| Build type | Release |$' "$first_report"; then
                            printf 'benchmark binary did not report Release build type: %s\n' \
                                "$benchmark_binary" >&2
                            exit 3
                        fi
                        if ! grep -q '^| Coverage instrumentation | disabled |$' "$first_report"; then
                            printf 'benchmark binary has coverage instrumentation enabled; '
                            printf 'configure with UKUI_QUICK_ENABLE_COVERAGE=OFF\n' >&2
                            exit 3
                        fi
                    fi
                    grep '^| Row | .* | steady |' "$profile_report"
                done
            done
        done
    done

    printf '\n## Resize/theme churn (separate from steady matrix)\n\n'
    printf '| Row | Cache | Profile | Keys target | Configured exact | Tick key range | Cumulative observed | Hosts | Physical px | Cadence target | Ticks submitted | Actual FPS | Source executor p95 ms | Queue p95 ms | Raster exec p95 ms | Raster completion p95 ms | GUI batch p95 ms | Host commit p95 ms | Raster jobs | Cache hits | Coalesced | Superseded | Dropped/stale | GUI batches | Budget |\n'
    printf '| --- | --- | --- | ---: | ---: | --- | ---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: | --- |\n'
    churn_report="$work_dir/cold-56-24-60-resize-theme.md"
    run_profile cold 56 24 60 resize-theme "$churn_report"
    grep '^| Row | .* | resize-theme |' "$churn_report"

    printf '\n## Resource hashes and environment\n\n'
    sed -n '/^## Environment$/,/^## Resource SHA-256$/p' "$first_report" |
        sed '/^## Resource SHA-256$/d'
    printf '## Resource SHA-256\n\n'
    sed -n '/^## Resource SHA-256$/,/^## Measurements$/p' "$first_report" |
        sed -e '/^## Resource SHA-256$/d' -e '/^## Measurements$/d'
} >"$report_path"

printf 'benchmark matrix report: %s\n' "$report_path"
