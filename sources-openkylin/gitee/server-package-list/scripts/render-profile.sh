#!/usr/bin/env bash
set -euo pipefail

usage() {
    cat <<'USAGE'
Usage:
  scripts/render-profile.sh <profile> [-o output]

Examples:
  scripts/render-profile.sh server-qemu-riscv64.img
  scripts/render-profile.sh server-amd64.iso
  scripts/render-profile.sh normal-qemu-riscv64.img -o /tmp/normal.packages

The profile dependency graph is read from package-lists/profiles.conf.
Each profile includes its dependencies first, then package-lists/<profile>.list
when that file exists.

Only profiles ending with .img or .iso can be rendered. Other profiles are
package-set building blocks used as dependencies.
USAGE
}

repo_root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
list_dir="${repo_root}/package-lists"
profile_file="${list_dir}/profiles.conf"
generated_dir="${repo_root}/generated"

if [[ $# -lt 1 ]]; then
    usage >&2
    exit 2
fi

profile="$1"
shift

output=""
while [[ $# -gt 0 ]]; do
    case "$1" in
        -o|--output)
            if [[ $# -lt 2 ]]; then
                echo "error: missing value for $1" >&2
                exit 2
            fi
            output="$2"
            shift 2
            ;;
        -h|--help)
            usage
            exit 0
            ;;
        *)
            echo "error: unknown argument: $1" >&2
            usage >&2
            exit 2
            ;;
    esac
done

if [[ ! -f "${profile_file}" ]]; then
    echo "error: missing profile dependency file: ${profile_file}" >&2
    exit 1
fi

if [[ -z "${output}" ]]; then
    mkdir -p "${generated_dir}"
    output="${generated_dir}/${profile}.packages"
else
    mkdir -p "$(dirname "${output}")"
fi

declare -A deps_by_profile=()
declare -A known_profile=()

while IFS= read -r line || [[ -n "${line}" ]]; do
    line="${line%%#*}"
    line="$(printf '%s' "${line}" | sed -e 's/^[[:space:]]*//' -e 's/[[:space:]]*$//')"
    [[ -z "${line}" ]] && continue

    if [[ "${line}" != *:* ]]; then
        echo "error: invalid profile line in ${profile_file}: ${line}" >&2
        exit 1
    fi

    name="${line%%:*}"
    deps="${line#*:}"
    name="$(printf '%s' "${name}" | sed -e 's/^[[:space:]]*//' -e 's/[[:space:]]*$//')"
    deps="$(printf '%s' "${deps}" | sed -e 's/^[[:space:]]*//' -e 's/[[:space:]]*$//')"

    if [[ -z "${name}" ]]; then
        echo "error: empty profile name in ${profile_file}" >&2
        exit 1
    fi

    known_profile["${name}"]=1
    deps_by_profile["${name}"]="${deps}"
done < "${profile_file}"

if [[ -z "${known_profile[${profile}]:-}" && ! -f "${list_dir}/${profile}.list" ]]; then
    echo "error: unknown profile '${profile}'" >&2
    echo "hint: add it to package-lists/profiles.conf or create package-lists/${profile}.list" >&2
    exit 1
fi

if [[ "${profile}" != *.img && "${profile}" != *.iso ]]; then
    echo "error: '${profile}' is not an image profile" >&2
    echo "hint: render a profile whose name ends with .img or .iso, such as server-qemu-riscv64.img" >&2
    exit 2
fi

declare -A visiting=()
declare -A visited=()
ordered_lists=()

expand_profile() {
    local name="$1"

    if [[ -n "${visited[${name}]:-}" ]]; then
        return
    fi

    if [[ -n "${visiting[${name}]:-}" ]]; then
        echo "error: cyclic profile dependency detected at '${name}'" >&2
        exit 1
    fi

    visiting["${name}"]=1

    local deps="${deps_by_profile[${name}]:-}"
    local dep
    for dep in ${deps}; do
        expand_profile "${dep}"
    done

    local list_file="${list_dir}/${name}.list"
    if [[ -f "${list_file}" ]]; then
        ordered_lists+=("${list_file}")
    elif [[ -z "${known_profile[${name}]:-}" ]]; then
        echo "error: dependency '${name}' has no profile entry and no ${name}.list" >&2
        exit 1
    fi

    unset "visiting[${name}]"
    visited["${name}"]=1
}

expand_profile "${profile}"

{
    printf '# Generated by scripts/render-profile.sh\n'
    printf '# Profile: %s\n' "${profile}"
    printf '# Source: package-lists/profiles.conf and package-lists/*.list\n'
    printf '# Do not edit this file manually.\n'
    printf '\n'
} > "${output}"

if [[ "${#ordered_lists[@]}" -gt 0 ]]; then
    awk '
        /^[[:space:]]*$/ { next }
        /^[[:space:]]*#/ { next }
        {
            sub(/^[[:space:]]+/, "")
            sub(/[[:space:]]+$/, "")
            if (!seen[$0]++) {
                print
            }
        }
    ' "${ordered_lists[@]}" >> "${output}"
fi

printf 'Rendered %s -> %s\n' "${profile}" "${output}"
printf 'Included lists:\n'
printf '  %s\n' "${ordered_lists[@]}"
