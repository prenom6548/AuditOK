def search_entries(keyword: str) -> list:
    """
    搜索会计分录
    
    Args:
        keyword: 搜索关键词
        
    Returns:
        list: 匹配的分录列表
    """
    results = []
    keyword = keyword.lower()
    
    for name, entry in JOURNAL_ENTRY_TEMPLATES.items():
        if keyword in name.lower() or keyword in entry.get("description", "").lower():
            results.append({
                "name": name,
                "description": entry["description"],
                "entry": entry["entry"],
                "note": entry.get("note", "")
            })
    
    return results


def get_entry(name: str) -> dict:
    """
    获取指定名称的会计分录
    
    Args:
        name: 分录名称
        
    Returns:
        dict: 分录详情
    """
    return JOURNAL_ENTRY_TEMPLATES.get(name, None)


def generate_entry_report(entries: list) -> str:
    """
    生成会计分录报告
    
    Args:
        entries: 分录列表
        
    Returns:
        str: 格式化报告
    """
    if not entries:
        return "未找到相关分录"
    
    report = ["## 会计分录查询结果\n"]
    
    for i, entry in enumerate(entries, 1):
        report.append(f"### {i}. {entry['name']}\n")
        report.append(f"**业务描述**：{entry['description']}\n")
        report.append(f"**会计分录**：\n```\n{entry['entry']}\n```\n")
        if entry.get("note"):
            report.append(f"**备注**：{entry['note']}\n")
        report.append("---\n")
    
    return "\n".join(report)


